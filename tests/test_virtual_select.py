async def test_one_select_per_production_meter():
    """Test only Production meters get a select, named by inverter and meter."""
    hub = _hub(
        [
            _meter(),
            _meter(MeterRole.EXPORT_IMPORT, meter_id=2),
            _meter(unit_id=2, meter_id=1),
        ]
    )

    entities = await _setup(hub)

    assert [e.name for e in entities] == [
        "Production Meter I1 M1",
        "Production Meter I2 M1",
    ]
    assert entities[0].unique_id == "entry1_system_production_meter_I1M1"
    assert entities[0].options == ["Inverter Only", "Whole Site"]
    # scopes are set when the entities restore, not at setup
    assert hub.system.production_meter_scopes == {}


async def test_disabled_select_uses_inverter_only():
    """Test a disabled select is not added and its meter is Inverter Only."""
    hub = _hub([_meter(), _meter(unit_id=2, meter_id=1)])
