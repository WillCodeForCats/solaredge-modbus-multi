@pytest.mark.parametrize(("cls", "suffix", "block", "field", "flag"), CASES)
class TestNumbers:
    """Behavior shared by every number entity."""

    def test_unique_id(self, cls, suffix, block, field, flag):
        """The unique id is built from the platform uid base."""
        entity = cls(_platform(), None, _coordinator())
        assert entity.unique_id == f"inverter_1{suffix}"

    def test_available_and_value(self, cls, suffix, block, field, flag):
        """A valid value is available and reported."""
        entity = cls(_default_platform(cls), None, _coordinator())
        assert entity.available
        assert entity.native_value == VALUES[cls]

    def test_unavailable_when_update_failed(self, cls, suffix, block, field, flag):
        """Unavailable when the coordinator update failed."""
        entity = cls(_default_platform(cls), None, _coordinator(False))
        assert not entity.available

    def test_unavailable_when_unsupported(self, cls, suffix, block, field, flag):
        """Unavailable when the inverter does not support the block."""
        platform = _default_platform(cls)
        setattr(platform, flag, False)
        assert not cls(platform, None, _coordinator()).available

    def test_unavailable_for_invalid_values(self, cls, suffix, block, field, flag):
        """Unavailable for None, not implemented, and out of range values."""
        for value in [None, *INVALID[cls]]:
            platform = _default_platform(cls)
            setattr(getattr(platform, block), field, value)
            assert not cls(platform, None, _coordinator()).available, value

    async def test_set_native_value(self, cls, suffix, block, field, flag):
        """Setting a value writes it to the block and requests a refresh."""
        platform = _platform()
        entity = cls(platform, None, _coordinator())

        await entity.async_set_native_value(12.0)

        value, kwargs = WRITES[cls]
        platform.write.assert_awaited_once_with(
            getattr(platform, block), field, value, **kwargs
        )
        assert type(platform.write.call_args.args[2]) is type(value)
        entity.coordinator.async_request_refresh.assert_awaited_once_with()


