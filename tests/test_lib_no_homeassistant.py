"""Check that the lib package stays free of Home Assistant imports.

lib/ is staged for extraction into a standalone library, so nothing in it may
import homeassistant or reach back into the integration package.

Test file generated by Claude Code.
"""

import ast
from pathlib import Path

import pytest

LIB_DIR = (
    Path(__file__).parent.parent
    / "custom_components"
    / "solaredge_modbus_multi"
    / "lib"
)


def _imported_modules(path: Path) -> list[tuple[int, str, int]]:
    """Return (line, module, relative level) for every import in a file."""
    tree = ast.parse(path.read_text(), filename=str(path))
    found = []
    for node in ast.walk(tree):
        if isinstance(node, ast.Import):
            found.extend((node.lineno, alias.name, 0) for alias in node.names)
        elif isinstance(node, ast.ImportFrom):
            found.append((node.lineno, node.module or "", node.level))
    return found


@pytest.mark.parametrize("path", sorted(LIB_DIR.glob("*.py")), ids=lambda p: p.name)
def test_lib_module_has_no_homeassistant_imports(path: Path):
    """Test lib modules import neither homeassistant nor the integration."""
    for line, module, level in _imported_modules(path):
        assert module.split(".")[0] != "homeassistant", f"{path.name}:{line}"
        assert "custom_components" not in module, f"{path.name}:{line}"
        assert level <= 1, f"{path.name}:{line} imports from outside lib"
