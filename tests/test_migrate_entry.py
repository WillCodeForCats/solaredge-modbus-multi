"""Tests for migrating config entries to the connection mode option.

Test module generated by Claude Code.
"""

from homeassistant.const import CONF_HOST, CONF_NAME, CONF_PORT
from pytest_homeassistant_custom_component.common import MockConfigEntry

from custom_components.solaredge_modbus_multi import async_migrate_entry
from custom_components.solaredge_modbus_multi.const import DOMAIN, ConfName

ENTRY_DATA = {
    CONF_NAME: "SolarEdge",
    CONF_HOST: "127.0.0.1",
    CONF_PORT: 1502,
    ConfName.DEVICE_LIST: [1],
}


def _make_entry(options):
    return MockConfigEntry(
        domain=DOMAIN,
        data=ENTRY_DATA,
        options=options,
        version=2,
        minor_version=3,
    )


async def test_close_after_polling_becomes_the_connection_mode(hass):
    """Test the old close_after_polling option keeps its behavior."""
    entry = _make_entry({"close_after_polling": True})
    entry.add_to_hass(hass)

    assert await async_migrate_entry(hass, entry)

    assert "close_after_polling" not in entry.options
    assert entry.options[ConfName.CONNECTION_MODE] == "own_close_after_polling"
    assert entry.minor_version == 4


async def test_close_after_polling_false_sets_no_connection_mode(hass):
    """Test the old option being off leaves the connection mode unset."""
    entry = _make_entry({"close_after_polling": False})
    entry.add_to_hass(hass)

    assert await async_migrate_entry(hass, entry)

    assert "close_after_polling" not in entry.options
    assert ConfName.CONNECTION_MODE not in entry.options
    assert entry.minor_version == 4


async def test_migration_without_the_old_option_keeps_other_options(hass):
    """Test other options are left alone."""
    entry = _make_entry({ConfName.REQUEST_TIMEOUT: 7})
    entry.add_to_hass(hass)

    assert await async_migrate_entry(hass, entry)

    assert dict(entry.options) == {ConfName.REQUEST_TIMEOUT: 7}
    assert entry.minor_version == 4
