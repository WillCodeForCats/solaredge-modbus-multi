async def test_pr_108_no_sunspec_device_attributes_for_unknown_did(hass):
    """Unknown SunSpec device IDs don't add a sunspec_device attribute."""
    connection, unit = _single_inverter()
    put(unit, MeterInfo, METER_INFO)
    put(unit, MeterData, METER_DATA)
    hub = await _init_hub(hass, connection, {ConfName.DETECT_METERS: True})
    coordinator = SimpleNamespace(last_update_success=True)
    inverter_device = SolarEdgeInverterDevice(hub.inverters[0], None, coordinator)
    meter_device = SolarEdgeMeterDevice(hub.meters[0], None, coordinator)

    assert inverter_device.extra_state_attributes["sunspec_device"]
    assert meter_device.extra_state_attributes["sunspec_device"]

    hub.inverters[0].inverter_data._values["C_SunSpec_DID"] = 999
    hub.meters[0].meter_data._values["C_SunSpec_DID"] = None
    inverter_attrs = inverter_device.extra_state_attributes
    meter_attrs = meter_device.extra_state_attributes

    assert inverter_attrs["sunspec_did"] == 999
    assert "sunspec_device" not in inverter_attrs
    assert "sunspec_did" not in meter_attrs
    assert "sunspec_device" not in meter_attrs


