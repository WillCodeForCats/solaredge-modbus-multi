@pytest.mark.parametrize("detected", [True, False, None])
async def test_power_control_entities_created_whatever_detection_says(hass, detected):
    """GPC and APC entities exist whether or not detection has succeeded.

    PR 974 created them only for inverters where detection had succeeded, so a
    probe timeout made them disappear. They are now always created and only
    show as unavailable, so the detection retry repair can bring them back.
    """
    inverter = SimpleNamespace(
        uid_base="inv",
        device_info=None,
        global_power_control=detected,
        advanced_power_control=detected,
        is_mmppt=False,
        use_status_vendor4=False,
        der_storage=[],
    )
    hub = SimpleNamespace(
        inverters=[inverter],
        meters=[],
        batteries=[],
        evses=[],
        option_detect_extras=True,
        option_storage_control=False,
        option_site_limit_control=False,
        option_virtual_system=False,
    )
    entry = SimpleNamespace(
        entry_id="entry1",
        runtime_data=SimpleNamespace(hub=hub, coordinator=SimpleNamespace()),
    )
    created = {}
    for platform in (number, select, sensor, button):
        add = MagicMock()
        await platform.async_setup_entry(hass, entry, add)
        created[platform] = {type(e) for e in add.call_args.args[0]}

    assert {
        number.SolarEdgeActivePowerLimitSet,
        number.SolarEdgeCosPhiSet,
        number.SolarEdgePowerReduce,
        number.SolarEdgeCurrentLimit,
    } <= created[number]
    assert select.SolarEdgeReactivePowerMode in created[select]
    assert {
        sensor.SolarEdgeRRCR,
        sensor.SolarEdgeActivePowerLimit,
        sensor.SolarEdgeCosPhi,
    } <= created[sensor]
    assert {
        button.SolarEdgeCommitControlSettings,
        button.SolarEdgeDefaultControlSettings,
    } <= created[button]
