@pytest.mark.parametrize(
    ("response", "expected"),
    [
        ([], SolarEdgeDeviceScanner.NOT_FOUND),
        ([0, 0, 0, 0, 0, 0], SolarEdgeDeviceScanner.NOT_FOUND),
        ([9, 9, 9, 9, 9, 9, 9], SolarEdgeDeviceScanner.NOT_FOUND),
        ("inverter", SolarEdgeDeviceScanner.FOUND_INV),
        ("inverter+extra", SolarEdgeDeviceScanner.FOUND),
    ],
)
def test_device_is_inverter(response, expected):
    """The response is matched against the inverter signature."""
    scanner = SolarEdgeDeviceScanner("host", 1502)
    request = SolarEdgeDeviceScanner.REQUEST.copy()
    request[0], request[1], request[6] = 1, 2, 3
    if response == "inverter":
        response = list(_inverter_response(request))
    elif response == "inverter+extra":
        response = [*_inverter_response(request), 0]

    assert scanner.device_is_inverter(request, response) == expected


def test_device_is_inverter_short_request():
    """A request too short to hold a device ID is not found."""
    scanner = SolarEdgeDeviceScanner("host", 1502)
    assert scanner.device_is_inverter([0, 0], [0] * 10) == scanner.NOT_FOUND


async def test_scan_device_id_connects_and_finds_inverter():
    """scan_device_id connects when needed and finds an inverter."""
    reader, writer = _connection(_inverter_response)
    scanner = SolarEdgeDeviceScanner("host", 1502)

    with _open_connection((reader, writer)):
        result = await scanner.scan_device_id(5)

    assert result == scanner.FOUND_INV
    request = list(writer.write.call_args.args[0])
    assert request[6] == 5
    assert (request[0], request[1]) == (0, 1)
    writer.drain.assert_awaited_once_with()


async def test_scan_device_id_other_device():
    """A response that does not match the signature is another device."""
    scanner = SolarEdgeDeviceScanner("host", 1502)
    scanner._reader, scanner._writer = _connection(_other_response)

    assert await scanner.scan_device_id(2) == scanner.FOUND


async def test_scan_device_id_transaction_wraps():
    """The transaction counter wraps at 65536."""
    scanner = SolarEdgeDeviceScanner("host", 1502)
    scanner._reader, scanner._writer = _connection(_inverter_response)
    scanner._transaction = 65535 + 256

    await scanner.scan_device_id(1)

    request = list(scanner._writer.write.call_args.args[0])
    assert (request[0], request[1]) == (1, 0)


@pytest.mark.parametrize("error", [asyncio.TimeoutError, OSError])
async def test_scan_device_id_retries_then_not_found(error):
    """Timeouts and network errors are retried, then the ID is not found."""
    scanner = SolarEdgeDeviceScanner("host", 1502, scan_retries=3)
    reader, writer = _connection()
    reader.read = AsyncMock(side_effect=error())
    scanner._reader, scanner._writer = reader, writer

    assert await scanner.scan_device_id(1, timeout=0.1) == scanner.NOT_FOUND
    assert reader.read.await_count == 3


async def test_scan_device_id_retry_succeeds():
    """A retry after a timeout can still find the inverter."""
    scanner = SolarEdgeDeviceScanner("host", 1502, scan_retries=3)
    reader, writer = _connection()
    # the request uses transaction 1 and device id 7
    reader.read = AsyncMock(
        side_effect=[TimeoutError(), _inverter_response([0, 1, 0, 0, 0, 6, 7])]
    )
    scanner._reader, scanner._writer = reader, writer

    assert await scanner.scan_device_id(7) == scanner.FOUND_INV
    assert writer.write.call_count == 2


async def test_scan_list_reports_progress():
    """scan_list returns the inverters and reports progress for each ID."""
    scanner = SolarEdgeDeviceScanner("host", 1502)
    results = {1: scanner.FOUND_INV, 2: scanner.FOUND, 3: scanner.NOT_FOUND}
    progress = AsyncMock()

    with patch.object(
        scanner, "scan_device_id", AsyncMock(side_effect=lambda i, _t: results[i])
    ):
        inverters = await scanner.scan_list([1, 2, 3], progress)

    assert inverters == [1]
    assert scanner.inverters == [1]
    assert progress.await_args_list == [call(0, 3), call(1, 3), call(2, 3), call(3, 3)]


