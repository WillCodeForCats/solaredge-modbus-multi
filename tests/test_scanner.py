def _inverter_response(request):
    """Build the inverter signature response for a request."""
    response = RESPONSE.copy()
    response[0] = request[0]
    response[1] = request[1]
    response[6] = request[6]
    return bytes(response)


def _socket_scanner(**kwargs):
    """Build a scanner that uses its own socket."""
    return SolarEdgeDeviceScanner(MagicMock(), "host", 1502, use_socket=True, **kwargs)


def _other_response(request):
    """Build a valid looking response from a device that is not an inverter."""
    return bytes([request[0], request[1], 0, 0, 0, 5, request[6], 3, 2, 0, 1])


def _connection(responder=None):
    """Build a fake reader and writer.

    The responder builds a response from the last request written.
    """
    writer = MagicMock()
    writer.drain = AsyncMock()
    writer.wait_closed = AsyncMock()
    reader = MagicMock()

    async def read(_size):
        request = list(writer.write.call_args.args[0])
        return responder(request)

    reader.read = AsyncMock(side_effect=read)
    return reader, writer


@pytest.fixture
def no_sleep():
    """Skip the delay between connection attempts."""
    with patch(f"{SCANNER}.asyncio.sleep", AsyncMock()) as sleep:
        yield sleep


def _open_connection(*results):
    """Patch open_connection to return or raise each result in turn."""
    return patch(
        f"{SCANNER}.asyncio.open_connection", AsyncMock(side_effect=list(results))
    )


async def test_connect_and_disconnect():
    """Calling connect opens a connection once and disconnect closes it."""
    reader, writer = _connection()
    scanner = _socket_scanner()

    with _open_connection((reader, writer)) as open_connection:
        await scanner.connect()
        await scanner.connect()

    open_connection.assert_awaited_once_with("host", 1502)
    await scanner.disconnect()
    writer.close.assert_called_once_with()
    writer.wait_closed.assert_awaited_once_with()
    assert scanner._writer is None
    assert scanner._reader is None

    # disconnecting again does nothing
    await scanner.disconnect()
    writer.close.assert_called_once_with()


async def test_connect_retries_after_timeout_and_os_error(no_sleep):
    """Calling connect retries after a timeout and a network error."""
    reader, writer = _connection()
    scanner = _socket_scanner(scan_retries=3)

    with _open_connection(
        TimeoutError(), OSError("refused"), (reader, writer)
    ) as open_connection:
        await scanner.connect()

    assert open_connection.await_count == 3
    assert no_sleep.await_args_list == [call(1.0), call(1.0)]
    assert scanner._writer is writer


