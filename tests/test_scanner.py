async def test_connect_holds_one_unit_until_disconnect():
    """Test connect holds one unit until disconnect."""
    entered, exited = [], []

    @asynccontextmanager
    async def _context(hass, params, unit_id):
        """Record entering and leaving the unit."""
        entered.append(unit_id)
        yield MagicMock()
        exited.append(unit_id)

    scanner = SolarEdgeDeviceScanner(MagicMock(), "127.0.0.1", 1502)
    with patch(TEMP_UNIT, _context):
        await scanner.connect()
        await scanner.connect()
        assert (len(entered), len(exited)) == (1, 0)
        await scanner.disconnect()
        await scanner.disconnect()

    assert (len(entered), len(exited)) == (1, 1)


