from types import SimpleNamespace
from unittest.mock import AsyncMock, MagicMock, patch

from homeassistant.helpers.update_coordinator import CoordinatorEntity

from custom_components.solaredge_modbus_multi.const import EVENT_STATUS_VENDOR
from custom_components.solaredge_modbus_multi.lib.const import (
    VENDOR4_STATUS,
    VENDOR_STATUS,
)
from custom_components.solaredge_modbus_multi.sensor import StatusVendor, StatusVendor4

COORDINATOR = SimpleNamespace(last_update_success=True)


def _entity(entity_class, value):
    """Return a status vendor entity with a mocked hass bus."""
    platform = SimpleNamespace(
        uid_base="inverter_1",
        device_info=None,
        use_status_vendor4=entity_class is StatusVendor4,
        inverter_data=SimpleNamespace(I_Status_Vendor=None, I_Status_Vendor4=None),
    )
    entity = entity_class(platform, None, COORDINATOR)
    entity.hass = MagicMock()
    entity.entity_id = "sensor.inverter_1_status_vendor"
    entity.registry_entry = SimpleNamespace(device_id="dev1")
    entity._async_error_entity_id = MagicMock(return_value="sensor.inverter_1_error")
    _set(entity, value)
    return entity


def _set(entity, value):
    """Set the code the entity reads."""
    data = entity._platform.inverter_data
    if isinstance(entity, StatusVendor4):
        data.I_Status_Vendor4 = value
    else:
        data.I_Status_Vendor = value


def _update(entity, value):
    """Set the code and run a coordinator update."""
    _set(entity, value)
    with patch.object(entity, "async_write_ha_state"):
        entity._handle_coordinator_update()


def _fired(entity):
    """Return the cause data (without the device and Error ids) of each event fired."""
    calls = entity.hass.bus.async_fire.call_args_list
    assert all(c.args[0] == EVENT_STATUS_VENDOR for c in calls)
    return [
        {
            k: v
            for k, v in c.args[1].items()
            if k not in ("device_id", "error_entity_id")
        }
        for c in calls
    ]


def test_status_vendor_change_records_text():
    """A code change fires an event with the code and text, under its context."""
    entity = _entity(StatusVendor, 0)
    _update(entity, 0)
    _update(entity, 17)

    assert _fired(entity) == [{"status_value": "17", "status_text": VENDOR_STATUS[17]}]
    call = entity.hass.bus.async_fire.call_args
    assert call.args[1]["device_id"] == "dev1"
    assert call.args[1]["error_entity_id"] == "sensor.inverter_1_error"
    assert "entity_id" not in call.args[1]
    assert entity._context is call.kwargs["context"]


def test_status_vendor_return_to_no_error_and_unknown_code():
    """Returning to zero is recorded; an unknown code has no text."""
    entity = _entity(StatusVendor, 0)
    _update(entity, 17)
    _update(entity, 17)
    _update(entity, 0)
    _update(entity, 12345)

    assert _fired(entity) == [
        {"status_value": "17", "status_text": VENDOR_STATUS[17]},
        {"status_value": "0", "status_text": VENDOR_STATUS[0]},
        {"status_value": "12345"},
    ]


def test_status_vendor_unavailable_resets():
    """After being unavailable, zero is not recorded but an error code is."""
    entity = _entity(StatusVendor, 0)
    _update(entity, 17)
    _update(entity, None)
    _update(entity, 0)
    _update(entity, None)
    _update(entity, 17)

    assert [d["status_value"] for d in _fired(entity)] == ["17", "17"]


def test_status_vendor4_change_records_text():
    """Vendor 4 codes are recorded in controller x error form with text."""
