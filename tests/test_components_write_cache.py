"""Tests for WriteCachedComponent.

Written values are shown until the next poll of the component, then the polled
values are used again.

Test file generated by Claude Code.
"""

from unittest.mock import patch

from modbus_connection.exceptions import IllegalDataValueError, ModbusTimeoutError
from modbus_connection.mock import MockModbusUnit
from modbus_connection.model import Component
import pytest

from custom_components.solaredge_modbus_multi.components import (
    AdvancedPowerControl,
    StorageControl,
)

CONTROL_MODE = 57348


async def _polled_storage_control(unit: MockModbusUnit, control_mode: int):
    """Return a StorageControl that has been polled once."""
    unit.holding[CONTROL_MODE] = control_mode
    component = StorageControl(unit)
    await component.async_update()
    return component


async def test_written_value_shown_until_next_poll(
    mock_modbus_unit: MockModbusUnit,
) -> None:
    """The written value is used until a poll, then the polled value is."""
    component = await _polled_storage_control(mock_modbus_unit, 1)

    await component.write("control_mode", 4)
    # The device reports something else, but nothing has polled it yet.
    mock_modbus_unit.holding[CONTROL_MODE] = 2
    assert component.control_mode == 4

    await component.async_update()
    assert component.control_mode == 2


async def test_write_during_poll_kept_until_following_poll(
    mock_modbus_unit: MockModbusUnit,
) -> None:
    """A poll running during a write may have read the old value, so keep it."""
    component = await _polled_storage_control(mock_modbus_unit, 1)

    async def poll_with_write(self, *, notify=True):
        await self.write("control_mode", 4)

    with patch.object(Component, "async_update", poll_with_write):
        await component.async_update()

    assert component.control_mode == 4

    mock_modbus_unit.holding[CONTROL_MODE] = 2
    await component.async_update()
    assert component.control_mode == 2


async def test_failed_poll_keeps_written_value(
    mock_modbus_unit: MockModbusUnit,
) -> None:
    """A poll that fails doesn't clear the written values."""
    component = await _polled_storage_control(mock_modbus_unit, 1)
    await component.write("control_mode", 4)

    mock_modbus_unit.fail_requests(ModbusTimeoutError("no response"))
    with pytest.raises(ModbusTimeoutError):
        await component.async_update()

    assert component.control_mode == 4


async def test_failed_write_not_kept(mock_modbus_unit: MockModbusUnit) -> None:
    """A write the device rejects leaves the polled value."""
    component = await _polled_storage_control(mock_modbus_unit, 1)

    mock_modbus_unit.fail_write(CONTROL_MODE, IllegalDataValueError("rejected"))
    with pytest.raises(IllegalDataValueError):
        await component.write("control_mode", 4)

    assert component.control_mode == 1


async def test_commit_register_not_kept(mock_modbus_unit: MockModbusUnit) -> None:
    """Commit reads back a result code where 1 is an error, so it isn't kept."""
    component = AdvancedPowerControl(mock_modbus_unit)

    await component.write("CommitPwrCtlSettings", 1)
    await component.write("RestorePwrCtlDefaults", 1)

    assert component.CommitPwrCtlSettings is None
    assert component.RestorePwrCtlDefaults == 1
