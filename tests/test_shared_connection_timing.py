"""Tests for detecting shared connection timing interference.

Test module generated by Claude Code.
"""

from types import SimpleNamespace
from unittest.mock import AsyncMock, MagicMock, patch

from homeassistant.const import CONF_HOST, CONF_NAME, CONF_PORT
from modbus_connection.exceptions import ModbusConnectionError, ModbusTimeoutError
from modbus_connection.mock import MockModbusConnection

from custom_components.solaredge_modbus_multi.const import (
    DOMAIN,
    SLOW_TIMEOUT_FACTOR,
    SLOW_TIMEOUT_LIMIT,
    ConfDefaultInt,
)
from custom_components.solaredge_modbus_multi.hub import (
    SharedUnits,
    SolarEdgeModbusMultiHub,
    async_update_with_retry,
)

ENTRY_DATA = {CONF_NAME: "SolarEdge", CONF_HOST: "127.0.0.1", CONF_PORT: 1502}
CREATE_ISSUE = "custom_components.solaredge_modbus_multi.hub.ir.async_create_issue"

SLOW = ConfDefaultInt.REQUEST_TIMEOUT * SLOW_TIMEOUT_FACTOR + 1
FAST = ConfDefaultInt.REQUEST_TIMEOUT


def _make_hub(hass, connection):
    """Build a hub on the given connection."""
    hass.data[DOMAIN] = {"yaml": {}}
    return SolarEdgeModbusMultiHub(hass, "test_entry_id", ENTRY_DATA, {}, connection)


async def test_retry_reports_elapsed_time_of_timeouts_only():
    """Test the retry helper reports timeouts, and no other errors."""
    component = SimpleNamespace(
        async_update=AsyncMock(
            side_effect=[ModbusTimeoutError(), ModbusConnectionError(), None]
        )
    )
    on_timeout = MagicMock()

    await async_update_with_retry(component, on_timeout=on_timeout)

    on_timeout.assert_called_once()
    assert on_timeout.call_args.args[0] >= 0


async def test_slow_timeouts_report_once_on_shared_connection(hass):
    """Test enough slow timeouts create one issue, however many follow."""
    hub = _make_hub(hass, SharedUnits({}))

    with patch(CREATE_ISSUE) as create_issue:
        for _ in range(SLOW_TIMEOUT_LIMIT + 2):
            hub._note_timeout(SLOW)

    create_issue.assert_called_once()
    assert create_issue.call_args.args[2] == "shared_connection_timing_test_entry_id"
    assert create_issue.call_args.kwargs["translation_key"] == (
        "shared_connection_timing"
    )


async def test_slow_timeouts_below_the_limit_do_not_report(hass):
    """Test fewer slow timeouts than the limit create no issue."""
    hub = _make_hub(hass, SharedUnits({}))

    with patch(CREATE_ISSUE) as create_issue:
        for _ in range(SLOW_TIMEOUT_LIMIT - 1):
            hub._note_timeout(SLOW)

    create_issue.assert_not_called()


async def test_timeouts_within_our_request_timeout_do_not_report(hass):
    """Test timeouts that took about as long as our own timeout are ignored."""
    hub = _make_hub(hass, SharedUnits({}))

    with patch(CREATE_ISSUE) as create_issue:
        for _ in range(SLOW_TIMEOUT_LIMIT + 2):
            hub._note_timeout(FAST)

    create_issue.assert_not_called()


async def test_own_connection_never_reports(hass):
    """Test slow timeouts on our own connection create no issue."""
    hub = _make_hub(hass, MockModbusConnection())

    with patch(CREATE_ISSUE) as create_issue:
        for _ in range(SLOW_TIMEOUT_LIMIT + 2):
            hub._note_timeout(SLOW)

    create_issue.assert_not_called()
