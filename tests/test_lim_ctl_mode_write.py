"""Tests for SolarEdgeInverter.write_lim_ctl_mode_bits().

The site limit switches and the limit control mode select share the
E_Lim_Ctl_Mode register, so each change must start from the device's current
value and wait for any other change to finish.

Test file generated by Claude Code.
"""

import asyncio
from unittest.mock import patch

from homeassistant.const import CONF_HOST, CONF_NAME, CONF_PORT
from homeassistant.exceptions import HomeAssistantError
from modbus_connection.exceptions import ModbusTimeoutError
from modbus_connection.mock import MockModbusConnection
import pytest

from custom_components.solaredge_modbus_multi import hub as hub_module
from custom_components.solaredge_modbus_multi.const import DATA_YAML
from custom_components.solaredge_modbus_multi.hub import (
    SolarEdgeInverter,
    SolarEdgeModbusMultiHub,
)

ENTRY_DATA = {
    CONF_NAME: "SolarEdge",
    CONF_HOST: "127.0.0.1",
    CONF_PORT: 1502,
}
E_LIM_CTL_MODE = 57344


def _make_inverter(hass, mode):
    """Build an inverter on a mock connection with E_Lim_Ctl_Mode set to mode."""
    hass.data[DATA_YAML] = {}
    connection = MockModbusConnection()
    hub = SolarEdgeModbusMultiHub(hass, "test_entry_id", ENTRY_DATA, {}, connection)
    unit = connection.for_unit(1)
    unit.load_raw({"holding": dict.fromkeys((*range(57344, 57348), 57362, 57363), 0)})
    unit.holding[E_LIM_CTL_MODE] = mode
    return SolarEdgeInverter(1, hub), unit


async def test_change_starts_from_device_value_not_cached_value(hass):
    """A stale cached value does not overwrite bits set on the device."""
    inverter, unit = _make_inverter(hass, 0)
    await inverter.site_limit_control_data.async_update()
    unit.holding[E_LIM_CTL_MODE] = 0b101
    assert inverter.site_limit_control_data.E_Lim_Ctl_Mode == 0

    written = await inverter.write_lim_ctl_mode_bits(0, 1 << 10)

    assert written == 0b101 | (1 << 10)
    assert unit.holding[E_LIM_CTL_MODE] == 0b101 | (1 << 10)


async def test_clear_mask_keeps_other_bits(hass):
    """Clearing the mode bits leaves the switch bits alone."""
    inverter, unit = _make_inverter(hass, (1 << 11) | (1 << 10) | 0b100)

    written = await inverter.write_lim_ctl_mode_bits(0b111, 0b010)

    assert written == (1 << 11) | (1 << 10) | 0b010
    assert unit.holding[E_LIM_CTL_MODE] == written


async def test_concurrent_changes_keep_each_other(hass):
    """Two changes started together both end up in the register."""
    inverter, unit = _make_inverter(hass, 0)
    real_update = hub_module.async_update_with_retry

    async def slow_update(component):
        # Yield after the read so the other change runs before this one
        # writes, which is when an unlocked read-modify-write loses a bit.
        await real_update(component)
        await asyncio.sleep(0)

    with patch.object(hub_module, "async_update_with_retry", slow_update):
        await asyncio.gather(
            inverter.write_lim_ctl_mode_bits(0, 1 << 10),
            inverter.write_lim_ctl_mode_bits(0, 1 << 11),
        )

    assert unit.holding[E_LIM_CTL_MODE] == (1 << 10) | (1 << 11)


async def test_read_failure_raises_and_does_not_write(hass):
    """A failed read raises HomeAssistantError and leaves the register alone."""
    inverter, unit = _make_inverter(hass, 0b001)
    unit.fail_read(E_LIM_CTL_MODE, ModbusTimeoutError("no response"))

    with pytest.raises(HomeAssistantError, match="inverter ID 1"):
        await inverter.write_lim_ctl_mode_bits(0, 1 << 10)

    assert unit.holding[E_LIM_CTL_MODE] == 0b001


async def test_not_implemented_value_raises_and_does_not_write(hass):
    """A register reading 0xFFFF is not changed."""
    inverter, unit = _make_inverter(hass, 0xFFFF)

    with pytest.raises(HomeAssistantError, match="not available"):
        await inverter.write_lim_ctl_mode_bits(0, 1 << 10)

    assert unit.holding[E_LIM_CTL_MODE] == 0xFFFF
