def simulated_site() -> MockModbusConnection:
    """Build the simulated site."""
    connection = MockModbusConnection()
    load_unit_1(connection.for_unit(1))
    load_unit_2(connection.for_unit(2))
    load_unit_3(connection.for_unit(3))
    connection.for_unit(4).fail_requests(ModbusTimeoutError("no response"))
    return connection
