def put(
    unit: MockModbusUnit, component: type, values: dict[str, Any], offset: int = 0
) -> None:
    """Encode field values of a component class into the unit's registers."""
    for name, value in values.items():
        field = getattr(component, name)
        words = field.encode(value)
        for index, word in enumerate(words):
            unit.holding[field.address + offset + index] = word


def put_model(unit: MockModbusUnit, address: int, model_id: int, length: int):
    """Write a SunSpec model header."""
    unit.holding[address] = model_id
    unit.holding[address + 1] = length


def load_inverter(
    unit: MockModbusUnit,
    model: str,
    serial: str,
    version: str,
    data: dict[str, Any] | None = None,
) -> None:
    """Load the common and data blocks of an inverter."""
    put(
        unit,
        InverterCommon,
        {
            **INVERTER_COMMON,
            "C_Model": model,
            "C_Version": version,
            "C_SerialNumber": serial,
        },
    )
    put(unit, InverterData, {**INVERTER_DATA, **(data or {})})


def load_unit_1(unit: MockModbusUnit) -> None:
    """Load unit 1: inverter with MMPPT, meter, battery, controls, and DER."""
    load_inverter(unit, "SE10K-RWS", "7E123456", "0004.0020.0000")

    # SunSpec model chain: 1, 103, 160, meter 1 + 203, 713, end
    put_model(unit, 40121, 160, 48)
    put(unit, MmpptCommon, {"mmppt_DID": 160, "mmppt_Length": 48, "mmppt_Units": 2})
    put(unit, MmpptData, MMPPT_DATA)
    for index in range(2):
        put(unit, MmpptUnit, {**MMPPT_UNIT, "ID": index + 1}, offset=20 * index)

    meter_offset = METER_1_BASE - 40121
    put(unit, MeterInfo, METER_INFO, offset=meter_offset)
    put(unit, MeterData, METER_DATA, offset=meter_offset)

    # DER storage capacity (model 713): WHRtg, WHAvail, SoC, SoH, Sta, WH_SF, Pct_SF
    put_model(unit, DER_713_ADDRESS, 713, 7)
    for offset, value in enumerate([9800, 4900, 50, 98, 1, 0, 0], 2):
        unit.holding[DER_713_ADDRESS + offset] = value
    put_model(unit, DER_713_ADDRESS + 9, END_MODEL, 0)

    put(unit, BatteryInfo, BATTERY_INFO)
    put(unit, BatteryData, BATTERY_DATA)

    put(unit, GlobalDynamicPowerControl, GLOBAL_POWER_CONTROL)
    put(unit, AdvancedPowerControl, ADVANCED_POWER_CONTROL)
    put(unit, SiteLimitControl, SITE_LIMIT_CONTROL)
    put(unit, StorageControl, STORAGE_CONTROL)


def load_unit_2(unit: MockModbusUnit) -> None:
    """Load unit 2: older inverter without meters, batteries, or controls."""
    load_inverter(
        unit,
        "SE5000H",
        "7E654321",
        "0003.0019.0000",
        {"C_SunSpec_DID": 101, "I_Status_Vendor": 3},
    )
    put_model(unit, 40121, END_MODEL, 0)
    unit.fail_read(61440, IllegalDataAddressError())
    unit.fail_read(61696, IllegalFunctionError())
    unit.fail_read(57344, ModbusExceptionError(4, "not supported"))
    unit.fail_read(57348, ModbusExceptionError(4, "not supported"))
    # the meter and battery blocks are not implemented
    for address in (40121, 40295, 40469):
        unit.fail_read(address + 1, ModbusExceptionError(2, "illegal address"))
    unit.fail_read(57600, ModbusExceptionError(2, "illegal address"))
    unit.fail_read(57856, ModbusExceptionError(2, "illegal address"))
    unit.fail_read(58368, ModbusExceptionError(2, "illegal address"))


