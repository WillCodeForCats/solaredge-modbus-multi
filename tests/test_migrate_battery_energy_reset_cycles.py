"""Tests for the 2.3 -> 2.4 battery_energy_reset_cycles config migration.

Test module generated by Claude Code.
"""

from homeassistant.const import CONF_HOST, CONF_PORT
from homeassistant.helpers import issue_registry as ir
import pytest
from pytest_homeassistant_custom_component.common import MockConfigEntry

from custom_components.solaredge_modbus_multi import async_migrate_entry
from custom_components.solaredge_modbus_multi.const import DOMAIN, ConfName

ISSUE_ID = "battery_energy_reset_cycles_changed"


def _entry(options):
    return MockConfigEntry(
        domain=DOMAIN,
        version=2,
        minor_version=3,
        unique_id="192.168.1.50:1502",
        data={
            CONF_HOST: "192.168.1.50",
            CONF_PORT: 1502,
            ConfName.DEVICE_LIST: [1],
        },
        options=options,
    )


@pytest.mark.parametrize("old_value", [0, 1])
async def test_low_value_migrated_and_issue_raised(hass, old_value):
    """Test 0 or 1 becomes 2 and a repair issue is raised."""
    entry = _entry({ConfName.BATTERY_ENERGY_RESET_CYCLES: old_value})
    entry.add_to_hass(hass)

    assert await async_migrate_entry(hass, entry)

    assert entry.minor_version == 4
    assert entry.options[ConfName.BATTERY_ENERGY_RESET_CYCLES] == 2
    issue = ir.async_get(hass).async_get_issue(DOMAIN, ISSUE_ID)
    assert issue is not None
    assert issue.translation_placeholders == {
        "old_value": str(old_value),
        "new_value": "2",
    }


@pytest.mark.parametrize("options", [{}, {ConfName.BATTERY_ENERGY_RESET_CYCLES: 5}])
async def test_other_values_left_alone(hass, options):
    """Test unset or already valid values are untouched and raise no issue."""
    entry = _entry(options)
    entry.add_to_hass(hass)

    assert await async_migrate_entry(hass, entry)

    assert entry.minor_version == 4
    assert dict(entry.options) == options
    assert ir.async_get(hass).async_get_issue(DOMAIN, ISSUE_ID) is None
