async def test_setup_acquires_one_unit_per_device_id(hass, setup_mocks):
    """Test setup acquires one unit per device id."""
    hass.data[DOMAIN] = {"yaml": {}}
    entry = _make_entry(options={ConfName.REQUEST_TIMEOUT: 7})
    entry.add_to_hass(hass)
    units = {unit_id: MagicMock() for unit_id in (1, 2, 5)}

    with (
        patch(
            GET_UNIT, side_effect=lambda h, e, p, unit_id: units[unit_id]
        ) as get_unit,
        patch.object(hass.config_entries, "async_forward_entry_setups", AsyncMock()),
    ):
        assert await async_setup_entry(hass, entry)

    assert [call.args[3] for call in get_unit.call_args_list] == [1, 2, 5]
    for call in get_unit.call_args_list:
        assert call.args[1] is entry
        assert call.args[2].host == "127.0.0.1"
        assert call.args[2].port == 1502
    for unit in units.values():
        unit.set_message_spacing.assert_called_once_with(MESSAGE_SPACING)
        unit.require_timeout.assert_called_once_with(7)

    shared = setup_mocks.call_args.args[4]
    assert isinstance(shared, SharedUnits)
    for unit_id, unit in units.items():
        assert shared.for_unit(unit_id) is unit


