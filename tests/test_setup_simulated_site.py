async def _setup(hass, options=None):
    """Set up a config entry for the simulated site."""
    entry = MockConfigEntry(
        domain=DOMAIN,
        data=ENTRY_DATA,
        options=ALL_OPTIONS if options is None else options,
        unique_id="192.0.2.10:1502",
        version=2,
        minor_version=4,
    )
    entry.add_to_hass(hass)
    assert await hass.config_entries.async_setup(entry.entry_id)
    await hass.async_block_till_done()
    return entry


async def _enable_all_entities(hass, entry):
    """Enable every entity that is disabled by default, then reload."""
    entity_registry = er.async_get(hass)
    for entity in er.async_entries_for_config_entry(entity_registry, entry.entry_id):
        if entity.disabled_by is not None:
            entity_registry.async_update_entity(entity.entity_id, disabled_by=None)
    assert await hass.config_entries.async_reload(entry.entry_id)
    await hass.async_block_till_done()


def _state(hass, entry, unique_id):
    """Return the state of the entity with the unique id."""
    entity_registry = er.async_get(hass)
    platform = unique_id.split(":")[0] if ":" in unique_id else "sensor"
    unique_id = unique_id.split(":")[-1]
    entity_id = entity_registry.async_get_entity_id(platform, DOMAIN, unique_id)
    assert entity_id is not None, unique_id
    return hass.states.get(entity_id)


async def test_setup_finds_every_device(hass, connection):
    """Inverters, MMPPT units, meter, battery, and EVSE become devices."""
    entry = await _setup(hass)

    assert entry.state is ConfigEntryState.LOADED
    hub = entry.runtime_data.hub
    assert [i.inverter_unit_id for i in hub.inverters] == [1, 2]
    assert [(m.inverter_unit_id, m.meter_id) for m in hub.meters] == [(1, 1)]
    assert [(b.inverter_unit_id, b.battery_id) for b in hub.batteries] == [(1, 1)]
    assert [e.evse_unit_id for e in hub.evses] == [3]

    inverter_1, inverter_2 = hub.inverters
    assert inverter_1.is_mmppt
    assert len(inverter_1.mmppt_units) == 2
    assert inverter_1.use_status_vendor4
    assert len(inverter_1.der_storage) == 1
    assert inverter_1.has_battery is True
    assert inverter_1.has_global_power_control is True
    assert inverter_1.has_advanced_power_control is True
    assert inverter_1.has_site_limit_control is True
    assert inverter_1.has_storage_control is True

    assert not inverter_2.is_mmppt
    assert not inverter_2.use_status_vendor4
    assert inverter_2.has_battery is False
    assert inverter_2.has_global_power_control is False
    assert inverter_2.has_advanced_power_control is False
    assert inverter_2.has_site_limit_control is False
    assert inverter_2.has_storage_control is False

    devices = dr.async_entries_for_config_entry(dr.async_get(hass), entry.entry_id)
    names = sorted(device.name for device in devices)
    assert names == [
        "Solaredge E3",
        "Solaredge I1",
        "Solaredge I1 B1",
        "Solaredge I1 M1",
        "Solaredge I1 MPPT0",
        "Solaredge I1 MPPT1",
        "Solaredge I2",
    ]

    # unit 4 did not respond, so it gets a repair issue instead
    issue_registry = ir.async_get(hass)
    assert issue_registry.async_get_issue(
        DOMAIN, f"setup_inverter_id_failed_{entry.entry_id}_4"
    )


