"""Tests for the inverter fault cause shared by the Status and Problem entities.

Covers the inverter Status sensor recording the vendor status when it goes to
I_STATUS_FAULT, and the Status and Problem entities sharing one cause event
per poll.

Test file generated by Claude Code.
"""

from types import SimpleNamespace
from unittest.mock import MagicMock, patch

from pytest_homeassistant_custom_component.common import (
    MockEntityPlatform,
    async_capture_events,
)

from custom_components.solaredge_modbus_multi.binary_sensor import InverterProblem
from custom_components.solaredge_modbus_multi.const import EVENT_PROBLEM, VENDOR_STATUS
from custom_components.solaredge_modbus_multi.sensor import SolarEdgeInverterStatus


def _platform(status, vendor=17):
    """Return an inverter platform with the given status and vendor status."""
    return SimpleNamespace(
        uid_base="inverter_1",
        device_info=None,
        use_status_vendor4=False,
        inverter_data=SimpleNamespace(I_Status=status, I_Status_Vendor=vendor),
        cause_contexts={},
    )


def _entity(entity_class, platform, coordinator, bus, entity_id):
    """Return an entity of the platform using a shared mocked hass bus."""
    entity = entity_class(platform, None, coordinator)
    entity.hass = MagicMock()
    entity.hass.bus = bus
    entity.entity_id = entity_id
    entity.registry_entry = SimpleNamespace(device_id="dev1")
    entity._async_error_entity_id = MagicMock(return_value="sensor.inverter_1_error")
    return entity


def _poll(coordinator, platform, status, *entities):
    """Set the status, start a new poll, and update each entity."""
    platform.inverter_data.I_Status = status
    coordinator.last_update_success_time += 1
    for entity in entities:
        with patch.object(entity, "async_write_ha_state"):
            entity._handle_coordinator_update()


def _setup(status=4):
    """Return the platform, coordinator, bus, status and problem entities."""
    platform = _platform(status)
    coordinator = SimpleNamespace(last_update_success=True, last_update_success_time=0)
    bus = MagicMock()
    status_entity = _entity(
        SolarEdgeInverterStatus, platform, coordinator, bus, "sensor.i1_status"
    )
    problem_entity = _entity(
        InverterProblem, platform, coordinator, bus, "binary_sensor.i1_problem"
    )
    return platform, coordinator, bus, status_entity, problem_entity


def test_status_fault_records_vendor_status():
    """Going to fault fires a problem event with the vendor status."""
    platform, coordinator, bus, status, _ = _setup()
    _poll(coordinator, platform, 4, status)
    assert bus.async_fire.call_count == 0

    _poll(coordinator, platform, 7, status)

    call = bus.async_fire.call_args
    assert call.args == (
        EVENT_PROBLEM,
        {
            "device_id": "dev1",
            "status_value": 17,
            "status_text": VENDOR_STATUS[17],
            "error_entity_id": "sensor.inverter_1_error",
        },
    )
    assert status._context is call.kwargs["context"]


def test_status_leaving_fault_not_recorded():
    """Leaving fault or changing between other states fires no event."""
    platform, coordinator, bus, status, _ = _setup()
    _poll(coordinator, platform, 7, status)
    _poll(coordinator, platform, 4, status)
    _poll(coordinator, platform, 2, status)

    assert bus.async_fire.call_count == 1


def test_status_and_problem_share_one_event_per_poll():
    """Both entities going to fault in one poll fire one event and share it."""
    platform, coordinator, bus, status, problem = _setup()
    _poll(coordinator, platform, 4, status, problem)

    _poll(coordinator, platform, 7, status, problem)

    assert bus.async_fire.call_count == 1
    context = bus.async_fire.call_args.kwargs["context"]
    assert status._context is context
    assert problem._context is context


def test_shared_event_order_does_not_matter():
    """Whichever entity updates first fires the event."""
    platform, coordinator, bus, status, problem = _setup()
    _poll(coordinator, platform, 7, problem, status)

    assert bus.async_fire.call_count == 1
    assert status._context is problem._context


def test_new_fault_in_later_poll_fires_new_event():
    """A fault after clearing fires a new event, not the earlier one's context."""
    platform, coordinator, bus, status, problem = _setup()
    _poll(coordinator, platform, 7, status, problem)
    first = bus.async_fire.call_args.kwargs["context"]
    _poll(coordinator, platform, 4, status, problem)
    _poll(coordinator, platform, 7, status, problem)

    assert bus.async_fire.call_count == 2
    second = bus.async_fire.call_args.kwargs["context"]
    assert second is not first
    assert status._context is second
    assert problem._context is second


async def test_status_and_problem_states_share_event_context(hass):
    """With real state writes, both fault states carry the one event's context."""
    platform = _platform(4)
    coordinator = MagicMock(last_update_success=True, last_update_success_time=0)
    status = SolarEdgeInverterStatus(platform, None, coordinator)
    problem = InverterProblem(platform, None, coordinator)
    events = async_capture_events(hass, EVENT_PROBLEM)
    await MockEntityPlatform(hass, domain="sensor").async_add_entities([status])
    await MockEntityPlatform(hass, domain="binary_sensor").async_add_entities([problem])
    assert events == []

    platform.inverter_data.I_Status = 7
    coordinator.last_update_success_time = 1
    status._handle_coordinator_update()
    problem._handle_coordinator_update()

    assert len(events) == 1
    assert "entity_id" not in events[0].data
    assert hass.states.get(status.entity_id).state == "I_STATUS_FAULT"
    assert hass.states.get(problem.entity_id).state == "on"
    assert hass.states.get(status.entity_id).context.id == events[0].context.id
    assert hass.states.get(problem.entity_id).context.id == events[0].context.id
