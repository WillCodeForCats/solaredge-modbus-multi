from homeassistant.core import Event, HomeAssistant
from homeassistant.helpers import device_registry as dr
import pytest
from pytest_homeassistant_custom_component.common import MockConfigEntry

from custom_components.solaredge_modbus_multi.const import (
    DOMAIN,
    EVENT_METER_EVENTS,
    EVENT_PROBLEM,
    EVENT_STATUS_VENDOR,
)
from custom_components.solaredge_modbus_multi.logbook import async_describe_events


def _describer(hass: HomeAssistant, event_type=EVENT_PROBLEM):
    """Return the describe callback registered for an event type."""
    registered = {}

    def describe_event(domain, event_type, describer):
        registered[(domain, event_type)] = describer

    async_describe_events(hass, describe_event)
    return registered[(DOMAIN, event_type)]


@pytest.mark.parametrize(
    ("data", "name"),
    [
        ({"status_value": "3x2", "status_text": "Over Temp"}, "Over Temp (3x2)"),
        ({"status_value": 12345}, "Status 12345"),
        ({}, "Fault"),
        (
            {
                "events": ["POWER_FAILURE", "OEM1"],
                "events_text": ["Loss of power or phase", "OEM1"],
            },
            "Loss of power or phase; OEM1",
        ),
    ],
)
async def test_describe_problem(hass: HomeAssistant, data, name):
    """The name is the cause and the message is the device."""
    described = _describer(hass)(Event(EVENT_PROBLEM, data))
    assert described == {"name": name, "message": "SolarEdge"}


async def test_describe_uses_device_name(hass: HomeAssistant):
    """The message is the device name, preferring the user's name."""
    entry = MockConfigEntry(domain=DOMAIN)
    entry.add_to_hass(hass)
    registry = dr.async_get(hass)
    device = registry.async_get_or_create(
        config_entry_id=entry.entry_id,
        identifiers={(DOMAIN, "inverter_1")},
        name="SolarEdge I1",
    )
    describe = _describer(hass)
    event = Event(EVENT_PROBLEM, {"device_id": device.id})

    assert describe(event)["message"] == "SolarEdge I1"

    registry.async_update_device(device.id, name_by_user="Garage Inverter")
    assert describe(event)["message"] == "Garage Inverter"


