@pytest.mark.parametrize(
    ("event_type", "data", "name"),
    [
        (EVENT_PROBLEM, {"status_value": 17}, "Status 17"),
        (EVENT_STATUS_VENDOR, {"status_value": "3x2"}, "Status 3x2"),
        (EVENT_METER_EVENTS, {"events_text": ["OEM1"]}, "OEM1"),
    ],
)
async def test_describe_links_error_sensor(hass: HomeAssistant, event_type, data, name):
    """An event naming the Error sensor links to it, with the cause as message.

    The frontend shows a linked entry's entity and device in place of its
    name, so the message must carry the cause.
    """
    describe = _describer(hass, event_type)
    linked = describe(Event(event_type, {**data, "error_entity_id": "sensor.i1_error"}))
    assert linked == {"name": name, "message": name, "entity_id": "sensor.i1_error"}
    assert describe(Event(event_type, data)) == {"name": name, "message": "SolarEdge"}


async def test_error_entity_id_found_in_registry(hass: HomeAssistant):
    """A cause entity finds its device's Error sensor by unique id."""
    platform = SimpleNamespace(uid_base="inverter_1", device_info=None)
    entity = InverterProblem(platform, None, None)
    entity.hass = hass
    assert entity._async_error_entity_id() is None

    registry = er.async_get(hass)
    registry.async_get_or_create("sensor", "other_domain", "inverter_1_error")
    assert entity._async_error_entity_id() is None

    error = registry.async_get_or_create("sensor", DOMAIN, "inverter_1_error")
    assert entity._async_error_entity_id() == error.entity_id
