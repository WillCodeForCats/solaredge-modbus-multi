def _hub_for_device_init(hass):
    hub = _make_hub(hass, "test_entry")
    hub.inverter_common[1] = SimpleNamespace(
        C_Model=INVERTER_MODEL, C_SerialNumber=INVERTER_SERIAL
    )
    hub.mmppt_common[1] = None
    return hub


@pytest.mark.parametrize("error", COMM_ERRORS)
async def test_battery_init_comm_error_raises_not_responding(hass, error):
    """Test battery init_device turns communication errors into DeviceNotResponding."""
    hub = _hub_for_device_init(hass)
    hub.connection.for_unit(1).fail_requests(error)
    battery = SolarEdgeBattery(1, 1, hub)

    assert battery.uid_base == BATTERY_UID
    with pytest.raises(DeviceNotResponding):
        await battery.init_device()


async def test_battery_init_exception_response_raises_invalid(hass):
    """Test battery init_device keeps a Modbus exception response as DeviceInvalid."""
    hub = _hub_for_device_init(hass)
    hub.connection.for_unit(1).fail_requests(IllegalDataAddressError())
    battery = SolarEdgeBattery(1, 1, hub)

    with pytest.raises(DeviceInvalid):
        await battery.init_device()


