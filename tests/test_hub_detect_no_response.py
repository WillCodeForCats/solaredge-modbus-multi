"""Tests for meter and battery detection when a device does not respond.

A known meter or battery that does not respond during detection fails the
hub setup so Home Assistant retries it, instead of silently dropping the
device. An unknown slot that does not respond is skipped with a warning.

Test module generated by Claude Code.
"""

import logging
from types import SimpleNamespace
from unittest.mock import AsyncMock, MagicMock, patch

from homeassistant.const import CONF_HOST, CONF_NAME, CONF_PORT
from homeassistant.helpers import device_registry as dr
from modbus_connection.exceptions import (
    IllegalDataAddressError,
    ModbusConnectionError,
    ModbusProtocolError,
    ModbusTimeoutError,
)
from modbus_connection.mock import MockModbusConnection
import pytest
from pytest_homeassistant_custom_component.common import MockConfigEntry

from custom_components.solaredge_modbus_multi.const import DOMAIN, ConfName
from custom_components.solaredge_modbus_multi.hub import (
    DeviceInvalid,
    DeviceNotResponding,
    HubInitFailed,
    SolarEdgeBattery,
    SolarEdgeMeter,
    SolarEdgeModbusMultiHub,
)

INVERTER_MODEL = "SE10K"
INVERTER_SERIAL = "7E000001"
BATTERY_UID = f"{INVERTER_MODEL}_{INVERTER_SERIAL}_B1"
METER_UID = f"{INVERTER_MODEL}_{INVERTER_SERIAL}_M1"

COMM_ERRORS = [
    ModbusTimeoutError("no response"),
    ModbusConnectionError("link down"),
    ModbusProtocolError("bad frame"),
]


class _FakeInverter:
    """Stand-in for SolarEdgeInverter that only fills what detection needs."""

    def __init__(self, unit_id, hub):
        self.inverter_unit_id = unit_id
        self.hub = hub
        self.uid_base = f"{INVERTER_MODEL}_{INVERTER_SERIAL}"
        self.inverter_common = MagicMock()
        self.init_der_storage = AsyncMock()
        self.read_modbus_data = AsyncMock()

    @property
    def device_info(self) -> dr.DeviceInfo:
        return dr.DeviceInfo(identifiers={(DOMAIN, self.uid_base)})

    async def init_device(self):
        self.hub.inverter_common[self.inverter_unit_id] = SimpleNamespace(
            C_Model=INVERTER_MODEL, C_SerialNumber=INVERTER_SERIAL
        )
        self.hub.mmppt_common[self.inverter_unit_id] = None


def _make_hub(hass, entry_id, *, meters=False, batteries=False):
    hass.data.setdefault(DOMAIN, {})["yaml"] = {}
    return SolarEdgeModbusMultiHub(
        hass,
        entry_id,
        {
            CONF_NAME: "SolarEdge",
            CONF_HOST: "127.0.0.1",
            CONF_PORT: 1502,
            ConfName.DEVICE_LIST: [1],
        },
        {
            ConfName.DETECT_METERS: meters,
            ConfName.DETECT_BATTERIES: batteries,
            ConfName.DETECT_EXTRAS: False,
        },
        MockModbusConnection(),
    )


def _add_entry(hass):
    entry = MockConfigEntry(domain=DOMAIN, data={})
    entry.add_to_hass(hass)
    return entry


def _register_device(hass, entry, uid_base):
    dr.async_get(hass).async_get_or_create(
        config_entry_id=entry.entry_id, identifiers={(DOMAIN, uid_base)}
    )


async def _run_detection(hub, *, battery_error=None, meter_error=None):
    battery_init = AsyncMock(side_effect=battery_error)
    meter_init = AsyncMock(side_effect=meter_error)
    with (
        patch(
            "custom_components.solaredge_modbus_multi.hub.SolarEdgeInverter",
            _FakeInverter,
        ),
        patch(
            "custom_components.solaredge_modbus_multi.hub.async_suns_scan_with_retry",
            AsyncMock(side_effect=ModbusTimeoutError("no scan")),
        ),
        patch.object(SolarEdgeBattery, "init_device", battery_init),
        patch.object(SolarEdgeMeter, "init_device", meter_init),
    ):
        await hub._async_init_solaredge()


async def test_known_battery_not_responding_fails_setup(hass):
    """Test a registered battery that does not respond fails hub setup."""
    entry = _add_entry(hass)
    _register_device(hass, entry, BATTERY_UID)
    hub = _make_hub(hass, entry.entry_id, batteries=True)

    with pytest.raises(HubInitFailed, match="I1B1 was detected before"):
        await _run_detection(hub, battery_error=DeviceNotResponding("timeout"))


async def test_unknown_battery_not_responding_is_skipped_with_warning(hass, caplog):
    """Test an unregistered battery slot that does not respond is skipped."""
    entry = _add_entry(hass)
    hub = _make_hub(hass, entry.entry_id, batteries=True)

    with caplog.at_level(logging.WARNING):
        await _run_detection(hub, battery_error=DeviceNotResponding("timeout"))

    assert hub.batteries == []
    assert "Battery I1B1 not detected, no response: timeout" in caplog.text


async def test_battery_registered_to_other_entry_is_skipped(hass):
    """Test a battery registered only to another config entry is skipped."""
    other_entry = _add_entry(hass)
    _register_device(hass, other_entry, BATTERY_UID)
    entry = _add_entry(hass)
    hub = _make_hub(hass, entry.entry_id, batteries=True)

    await _run_detection(hub, battery_error=DeviceNotResponding("timeout"))

    assert hub.batteries == []


async def test_known_battery_invalid_is_still_skipped(hass, caplog):
    """Test a registered battery that reports invalid data is skipped quietly."""
    entry = _add_entry(hass)
    _register_device(hass, entry, BATTERY_UID)
    hub = _make_hub(hass, entry.entry_id, batteries=True)

    with caplog.at_level(logging.WARNING):
        await _run_detection(hub, battery_error=DeviceInvalid("rating <=0"))

    assert hub.batteries == []
    assert "not detected" not in caplog.text


