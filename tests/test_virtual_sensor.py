"""Tests for the virtual system sensors in virtual_sensor.py.

The expected values follow the template sensors for a system without batteries in
the wiki page "Template-Sensors-for-Power-and-Energy", summed across inverters.

These tests were generated by Claude Code.
"""

from types import SimpleNamespace
from unittest.mock import MagicMock

import pytest

from custom_components.solaredge_modbus_multi.const import (
    DOMAIN,
    MeterRole,
    SunSpecNotImpl,
)
from custom_components.solaredge_modbus_multi.sensor import async_setup_entry
from custom_components.solaredge_modbus_multi.virtual_sensor import (
    SolarACPower,
    SystemPower,
    _power_keys,
    _scaled,
    async_virtual_system_entities,
    calculate_power,
)

COORDINATOR = SimpleNamespace(last_update_success=True)
FAILED_COORDINATOR = SimpleNamespace(last_update_success=False)


def _inverter(ac=0, dc=0, ac_sf=0, dc_sf=0):
    return SimpleNamespace(
        inverter_data=SimpleNamespace(
            AC_Power=ac, AC_Power_SF=ac_sf, I_DC_Power=dc, I_DC_Power_SF=dc_sf
        )
    )


def _meter(role=MeterRole.EXPORT_IMPORT, power=0, sf=0):
    return SimpleNamespace(
        meter_role=role,
        meter_data=SimpleNamespace(AC_Power=power, AC_Power_SF=sf),
    )


def _hub(inverters=(), meters=(), batteries=()):
    hub = SimpleNamespace(
        inverters=list(inverters),
        meters=list(meters),
        batteries=list(batteries),
        option_virtual_system=True,
        evses=[],
        der_batteries=[],
    )
    hub.system = SimpleNamespace(uid_base="entry1_system", hub=hub, device_info={})
    return hub


def _power(hub, key, coordinator=COORDINATOR):
    return SystemPower(hub.system, None, coordinator, key)


def test_scaled():
    """Test the scale factor is applied and invalid values give None."""
    assert _scaled(1234, -1) == pytest.approx(123.4)
    assert _scaled(5, 2) == 500
    assert _scaled(None, 0) is None
    assert _scaled(1, None) is None
    assert _scaled(SunSpecNotImpl.INT16, 0) is None
    assert _scaled(1, SunSpecNotImpl.INT16) is None
    assert _scaled(1, 99) is None


# ---- wiki "Single inverter, Single Import / Export meter" ----


@pytest.mark.parametrize(
    ("meter", "expected"),
    [
        # exporting 200 W
        (
            200,
            {
                "solar_generation": 1000,
                "consumption": 750,
                "grid_load": 0,
                "pv_grid": 200,
                "pv_load": 800,
            },
        ),
        # importing 300 W
        (
            -300,
            {
                "solar_generation": 1000,
                "consumption": 1250,
                "grid_load": 300,
                "pv_grid": 0,
                "pv_load": 1000,
            },
        ),
    ],
)
def test_power(meter, expected):
    """Test the formulas for one inverter and an import/export meter."""
    hub = _hub([_inverter(ac=950, dc=1000)], [_meter(power=meter)])

    assert calculate_power(hub) == expected


def test_power_sums_multiple_inverters():
    """Test every inverter is added without any extra configuration."""
    hub = _hub(
        [_inverter(ac=950, dc=1000), _inverter(ac=550, dc=600)],
        [_meter(power=-100)],
    )

    assert calculate_power(hub) == {
        "solar_generation": 1600,
        "consumption": 1600,
        "grid_load": 100,
        "pv_grid": 0,
        "pv_load": 1600,
    }


def test_power_applies_scale_factors():
    """Test each device's own scale factor is applied before summing."""
    hub = _hub(
        [
            _inverter(ac=9500, dc=10000, ac_sf=-1, dc_sf=-1),
            _inverter(ac=55, dc=60, ac_sf=1, dc_sf=1),
        ],
        [_meter(power=-10, sf=1)],
    )

    result = calculate_power(hub)
    assert result["solar_generation"] == pytest.approx(1600)
    assert result["consumption"] == pytest.approx(1600)


def test_consumption_is_the_plain_net():
    """Test consumption is not limited to zero, like the wiki template."""
    hub = _hub([_inverter(ac=100, dc=100)], [_meter(power=300)])

    assert calculate_power(hub)["consumption"] == -200


def test_other_meter_roles_are_ignored():
    """Test only an Export+Import meter feeds the grid values."""
    hub = _hub(
        [_inverter(ac=500, dc=500)],
        [_meter(MeterRole.CONSUMPTION, 9999), _meter(MeterRole.EXPORT_IMPORT, 100)],
    )

    assert calculate_power(hub)["consumption"] == 400


def test_multiple_export_import_meters_are_summed():
    """Test more than one Export+Import meter is added together."""
    hub = _hub(
        [_inverter(ac=500, dc=500)],
        [_meter(power=100), _meter(power=50)],
    )

    assert calculate_power(hub)["consumption"] == 350


# ---- availability ----


@pytest.mark.parametrize(
    ("hub", "key"),
    [
        (
            _hub([_inverter(), _inverter(dc=SunSpecNotImpl.INT16)], [_meter()]),
            "solar_generation",
        ),
        (
            _hub([_inverter(), _inverter(ac=SunSpecNotImpl.INT16)], [_meter()]),
            "consumption",
        ),
        (_hub([_inverter()], [_meter(power=SunSpecNotImpl.INT16)]), "consumption"),
    ],
)
def test_one_invalid_device_makes_the_total_none(hub, key):
    """Test one invalid device makes the total None instead of a partial value."""
    assert calculate_power(hub)[key] is None


def test_invalid_inverter_dc_only_affects_dc_based_values():
    """Test unrelated values stay available when one input is invalid."""
    hub = _hub([_inverter(ac=500, dc=SunSpecNotImpl.INT16)], [_meter(power=100)])
    result = calculate_power(hub)

    assert result["solar_generation"] is None
    assert result["pv_load"] is None
    assert result["consumption"] == 400
    assert result["grid_load"] == 0


def test_power_sensor_availability_follows_value_and_coordinator():
    """Test the sensor is unavailable on invalid input or a failed update."""
    good = _hub([_inverter(dc=100)], [_meter()])
    bad = _hub([_inverter(dc=SunSpecNotImpl.INT16)], [_meter()])

    assert _power(good, "solar_generation").available
    assert not _power(bad, "solar_generation").available
    assert not _power(good, "solar_generation", FAILED_COORDINATOR).available


# ---- which sensors are created ----


@pytest.mark.parametrize(
    ("meters", "expected"),
    [
        ([], ["solar_generation"]),
        (
            [_meter()],
            ["solar_generation", "consumption", "grid_load", "pv_grid", "pv_load"],
        ),
        ([_meter(MeterRole.PRODUCTION)], ["solar_generation"]),
        ([_meter(MeterRole.CONSUMPTION)], ["solar_generation"]),
    ],
)
def test_power_keys(meters, expected):
    """Test the sensor set depends on the meters present."""
    hub = _hub([_inverter()], meters)

    assert sorted(_power_keys(hub)) == sorted(expected)


def test_no_power_sensors_with_batteries():
    """Test systems with batteries are not supported yet, so no wiki sensors."""
    hub = _hub([_inverter()], [_meter()], [SimpleNamespace()])

    assert _power_keys(hub) == []


def test_every_key_has_a_calculation():
    """Test every sensor key created has a value in the calculation."""
    hub = _hub([_inverter()], [_meter()])

    assert set(_power_keys(hub)) <= set(calculate_power(hub))


def test_entities_empty_without_inverters():
    """Test no entities are created when there are no inverters."""
    assert async_virtual_system_entities(_hub(), None, COORDINATOR) == []


def test_entities_are_solar_ac_plus_one_power_per_key():
    """Test the entities created for an inverter with an import/export meter."""
    hub = _hub([_inverter()], [_meter()])
    entities = async_virtual_system_entities(hub, None, COORDINATOR)

    assert sum(isinstance(e, SolarACPower) for e in entities) == 1
    assert sum(isinstance(e, SystemPower) for e in entities) == 5


def test_entities_with_batteries_are_only_solar_ac():
    """Test a system with batteries only gets Solar AC Power for now."""
    hub = _hub([_inverter()], [_meter()], [SimpleNamespace()])
    entities = async_virtual_system_entities(hub, None, COORDINATOR)

    assert [type(e) for e in entities] == [SolarACPower]


def test_unique_ids_and_names():
    """Test ids come from the system device and names follow the wiki."""
    hub = _hub([_inverter()], [_meter()])

    power = _power(hub, "grid_load")
    assert power.unique_id == "entry1_system_power_grid_load"
    assert power.name == "Power - Grid - Load"

    assert SolarACPower(hub.system, None, COORDINATOR).unique_id == (
        "entry1_system_solar_ac_power"
    )


async def test_setup_entry_adds_no_system_sensors_when_option_off():
    """Test the sensor platform adds nothing for the system when the option is off."""
    hub = _hub()
    hub.option_virtual_system = False
    hass = SimpleNamespace(
        data={DOMAIN: {"entry1": {"hub": hub, "coordinator": COORDINATOR}}}
    )
    add = MagicMock()

    await async_setup_entry(hass, SimpleNamespace(entry_id="entry1"), add)

    add.assert_not_called()


# ---- Solar AC Power ----


def test_solar_ac_sums_inverters():
    """Test AC power sums all inverters."""
    hub = _hub([_inverter(ac=1000), _inverter(ac=250, ac_sf=1)])
    sensor = SolarACPower(hub.system, None, COORDINATOR)

    assert sensor.available
    assert sensor.native_value == 3500
    assert sensor.extra_state_attributes == {"source": "inverter"}


def test_solar_ac_clips_inverters_charging_from_grid():
    """Test an inverter drawing from the grid is not negative solar production."""
    hub = _hub([_inverter(ac=1000), _inverter(ac=-300)])

    assert SolarACPower(hub.system, None, COORDINATOR).native_value == 1000


def test_solar_ac_prefers_production_meters():
    """Test production meters are summed and used instead of the inverters."""
    hub = _hub(
        [_inverter(ac=1000)],
        [_meter(MeterRole.PRODUCTION, 900), _meter(MeterRole.PRODUCTION, 400)],
    )
    sensor = SolarACPower(hub.system, None, COORDINATOR)

    assert sensor.native_value == 1300
    assert sensor.extra_state_attributes == {"source": "meter"}


def test_solar_ac_does_not_fall_back_when_meter_invalid():
    """Test a bad production meter does not silently use the inverters."""
    hub = _hub(
        [_inverter(ac=1000)],
        [_meter(MeterRole.PRODUCTION, SunSpecNotImpl.INT16)],
    )

    assert not SolarACPower(hub.system, None, COORDINATOR).available
