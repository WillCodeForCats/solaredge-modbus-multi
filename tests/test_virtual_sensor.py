# ---- Solar AC Power ----


def test_solar_ac_sums_inverters():
    """Test AC power sums all inverters."""
    hub = _hub([_inverter(ac=1000), _inverter(ac=250, ac_sf=1)])
    sensor = SolarACPower(hub.system, None, COORDINATOR)

    assert sensor.available
    assert sensor.native_value == 3500
    assert sensor.extra_state_attributes == {"source": "inverter"}


def test_solar_ac_clips_inverters_charging_from_grid():
    """Test an inverter drawing from the grid is not negative solar production."""
    hub = _hub([_inverter(ac=1000), _inverter(ac=-300)])

    assert SolarACPower(hub.system, None, COORDINATOR).native_value == 1000


def test_solar_ac_prefers_production_meters():
    """Test production meters are summed and used instead of the inverters."""
    hub = _hub(
        [_inverter(ac=1000)],
        [
            _meter(MeterRole.PRODUCTION, 900),
            _meter(MeterRole.PRODUCTION, 400, meter_id=2),
        ],
    )
    sensor = SolarACPower(hub.system, None, COORDINATOR)

    assert sensor.native_value == 1300
    assert sensor.extra_state_attributes == {"source": "meter"}


def test_solar_ac_does_not_fall_back_when_meter_invalid():
    """Test a bad production meter does not silently use the inverters."""
    hub = _hub(
        [_inverter(ac=1000)],
        [_meter(MeterRole.PRODUCTION, SunSpecNotImpl.INT16)],
    )

    assert not SolarACPower(hub.system, None, COORDINATOR).available


def test_solar_ac_unavailable_with_storage_and_no_production_meter():
    """Test battery discharge is not reported as solar from the inverters."""
    hub = _hub([_inverter(ac=1000)], batteries=[SimpleNamespace()])
    sensor = SolarACPower(hub.system, None, COORDINATOR)

    assert sensor.native_value is None
    assert not sensor.available


def test_solar_ac_unavailable_with_storage_and_production_meter():
    """Test a Production meter on the inverter output is not used with batteries.

    DC coupled battery discharge goes through the inverter AC output too.
    """
    hub = _hub(
        [_inverter(ac=1000)],
        [_meter(MeterRole.PRODUCTION, 900)],
        batteries=[SimpleNamespace()],
    )

    assert SolarACPower(hub.system, None, COORDINATOR).native_value is None


def test_der_storage_alone_is_not_a_battery():
    """Test model 713 without a detected battery keeps the inverter values.

    Inverters can report SunSpec DER storage with no battery connected.
    """
    hub = _hub([_inverter(ac=1000, der_storage=[SimpleNamespace()])], [_meter()])

    assert not hub.system.has_storage
    assert len(hub.system.power_keys) == 5
    assert SolarACPower(hub.system, None, COORDINATOR).native_value == 1000


def test_skipped_inverter_makes_inverter_totals_unavailable():
    """Test a configured inverter skipped at setup does not give a low total.

    Values from the Export+Import meter alone are still available.
    """
    hub = _hub([_inverter(ac=1000, dc=1100)], [_meter(power=-300)])
    hub.skipped_inverter_ids = [2]

    assert hub.system.power_values == {
        "solar_generation": None,
        "consumption": None,
        "grid_load": 300,
        "pv_grid": 0,
        "pv_load": None,
    }
    assert SolarACPower(hub.system, None, COORDINATOR).native_value is None


def test_skipped_inverter_keeps_site_production_meter_solar():
    """Test Solar AC Power from a Whole Site Production meter needs no inverters."""
    hub = _hub([_inverter(ac=1000)], [_meter(MeterRole.PRODUCTION, 900)])
    hub.system.production_meter_scopes["I1M1"] = MeterScope.SITE
    hub.skipped_inverter_ids = [2]

    assert SolarACPower(hub.system, None, COORDINATOR).native_value == 900


def test_skipped_inverter_makes_inverter_production_meter_solar_unavailable():
    """Test an Inverter Only Production meter does not give a low total.

    The skipped inverter's own meters are missing with it.
    """
    hub = _hub([_inverter(ac=1000)], [_meter(MeterRole.PRODUCTION, 900)])
    hub.skipped_inverter_ids = [2]

    assert SolarACPower(hub.system, None, COORDINATOR).native_value is None


def test_solar_ac_inverter_production_meter_only_replaces_its_inverter():
    """Test an Inverter Only meter is used for its inverter, AC power for others."""
    hub = _hub(
        [_inverter(ac=1000), _inverter(ac=500, unit_id=2)],
        [_meter(MeterRole.PRODUCTION, 900)],
    )
    sensor = SolarACPower(hub.system, None, COORDINATOR)

    assert sensor.native_value == 1400
    assert sensor.extra_state_attributes == {"source": "mixed"}


def test_solar_ac_site_production_meter_replaces_all_inverters():
    """Test a Whole Site meter is used alone, ignoring Inverter Only meters."""
    hub = _hub(
        [_inverter(ac=1000), _inverter(ac=500, unit_id=2)],
        [
            _meter(MeterRole.PRODUCTION, 1600, unit_id=2),
            _meter(MeterRole.PRODUCTION, 900),
        ],
    )
    hub.system.production_meter_scopes["I2M1"] = MeterScope.SITE
    sensor = SolarACPower(hub.system, None, COORDINATOR)

    assert sensor.native_value == 1600
    assert sensor.extra_state_attributes == {"source": "meter"}


def test_solar_ac_unavailable_until_production_meter_scope_is_set():
    """Test the default scope is not used before the select has restored."""
    meter = _meter(MeterRole.PRODUCTION, 900)
    hub = _hub([_inverter(ac=1000)], [meter])
    hub.system.production_meter_scopes = {}

    assert hub.system.production_meter_scope(meter) == MeterScope.INVERTER
    assert SolarACPower(hub.system, None, COORDINATOR).native_value is None
