"""Tests for the meter sensors recording a cause in the logbook.

Covers meter_event_names and meter_event_texts, the Meter Events sensor
recording each change in the event bits, and the meter Problem sensor recording
its cause when it turns on.

Test file generated by Claude Code.
"""

from types import SimpleNamespace
from unittest.mock import AsyncMock, MagicMock, patch

from homeassistant.helpers.update_coordinator import CoordinatorEntity
import pytest

from custom_components.solaredge_modbus_multi.binary_sensor import MeterProblem
from custom_components.solaredge_modbus_multi.const import (
    EVENT_METER_EVENTS,
    EVENT_PROBLEM,
    METER_EVENTS_TEXT,
)
from custom_components.solaredge_modbus_multi.helpers import (
    meter_event_names,
    meter_event_texts,
)
from custom_components.solaredge_modbus_multi.sensor import MeterEvents

COORDINATOR = SimpleNamespace(last_update_success=True)


def _entity(entity_class, events):
    """Return a meter entity with a mocked hass bus."""
    platform = SimpleNamespace(
        uid_base="inverter_1_M1",
        device_info=None,
        meter_data=SimpleNamespace(M_Events=events),
    )
    entity = entity_class(platform, None, COORDINATOR)
    entity.hass = MagicMock()
    entity.entity_id = "sensor.inverter_1_m1"
    entity.registry_entry = SimpleNamespace(device_id="dev1")
    entity._async_error_entity_id = MagicMock(return_value="sensor.inverter_1_m1_error")
    return entity


def _update(entity, events):
    """Set the event bits and run a coordinator update."""
    entity._platform.meter_data.M_Events = events
    with patch.object(entity, "async_write_ha_state"):
        entity._handle_coordinator_update()


def _fired(entity, event_type):
    """Return the cause data (without the device and Error ids) of each event fired."""
    calls = entity.hass.bus.async_fire.call_args_list
    assert all(c.args[0] == event_type for c in calls)
    return [
        {
            k: v
            for k, v in c.args[1].items()
            if k not in ("device_id", "error_entity_id")
        }
        for c in calls
    ]


@pytest.mark.parametrize(
    ("value", "names"),
    [
        (0, []),
        (0b11, []),
        (0b1100, ["POWER_FAILURE", "UNDER_VOLTAGE"]),
        ((1 << 16) | (1 << 5), ["OVER_CURRENT", "OEM1"]),
    ],
)
def test_meter_event_names(value, names):
    """Names come from the defined bits, in bit order; bits 0-1 are undefined."""
    assert meter_event_names(value) == names


@pytest.mark.parametrize(
    ("value", "texts"),
    [
        (0, []),
        (0b11, []),
        (0b1100, [METER_EVENTS_TEXT[2], METER_EVENTS_TEXT[3]]),
        ((1 << 16) | (1 << 8) | (1 << 7), [METER_EVENTS_TEXT[7], "RESERVED1", "OEM1"]),
    ],
)
def test_meter_event_texts(value, texts):
    """Defined bits use their description; reserved and OEM bits use their name."""
    assert meter_event_texts(value) == texts


def test_meter_events_attributes():
    """The events attribute lists the active event names."""
    entity = _entity(MeterEvents, 0b1100)
    assert entity.extra_state_attributes == {
        "bits": f"{0b1100:032b}",
        "events": "['POWER_FAILURE', 'UNDER_VOLTAGE']",
    }


def test_meter_events_change_records_names():
    """Each change in the bits fires an event, including back to zero."""
    entity = _entity(MeterEvents, 0)
    _update(entity, 0)
    _update(entity, 0b1100)
    _update(entity, 0b1100)
    _update(entity, 1 << 16)
    _update(entity, 0)

    assert _fired(entity, EVENT_METER_EVENTS) == [
        {
            "status_value": 0b1100,
            "events": ["POWER_FAILURE", "UNDER_VOLTAGE"],
            "events_text": [METER_EVENTS_TEXT[2], METER_EVENTS_TEXT[3]],
        },
        {"status_value": 1 << 16, "events": ["OEM1"], "events_text": ["OEM1"]},
        {"status_value": 0, "events": [], "events_text": []},
    ]
    call = entity.hass.bus.async_fire.call_args
    assert entity._context is call.kwargs["context"]


async def test_meter_events_at_startup():
    """Active events when added are recorded; zero is not."""
    with patch.object(CoordinatorEntity, "async_added_to_hass", AsyncMock()):
        active = _entity(MeterEvents, 1 << 5)
        await active.async_added_to_hass()
        normal = _entity(MeterEvents, 0)
        await normal.async_added_to_hass()

    assert _fired(active, EVENT_METER_EVENTS) == [
        {
            "status_value": 1 << 5,
            "events": ["OVER_CURRENT"],
            "events_text": [METER_EVENTS_TEXT[5]],
        }
    ]
    assert _fired(normal, EVENT_METER_EVENTS) == []


def test_meter_problem_records_problem_events_only():
    """Turning on records only the problem bits; turning off records nothing."""
    entity = _entity(MeterProblem, 0)
    _update(entity, 0)
    _update(entity, (1 << 5) | (1 << 16))
    _update(entity, (1 << 5) | (1 << 2))
    _update(entity, 0)

    assert _fired(entity, EVENT_PROBLEM) == [
        {"events": ["OVER_CURRENT"], "events_text": [METER_EVENTS_TEXT[5]]}
    ]


def test_meter_event_links_meter_error_sensor():
    """The event names the meter's Error sensor for the logbook entry link."""
    entity = _entity(MeterEvents, 0)
    _update(entity, 0)
    _update(entity, 0b100)

    call = entity.hass.bus.async_fire.call_args
    assert call.args[1]["error_entity_id"] == "sensor.inverter_1_m1_error"
