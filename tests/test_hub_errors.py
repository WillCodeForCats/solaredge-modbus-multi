async def test_battery_that_never_answers_is_skipped(hass):
    """A battery slot that doesn't answer within the request timeout is skipped.

    Battery detection is tried once, so a silent slot can't hold up setup.
    """

    async def never_answers(self):
        await asyncio.sleep(10)

    hub, _ = _hub(
        hass,
        device_list=[1],
        options={ConfName.DETECT_BATTERIES: True, ConfName.REQUEST_TIMEOUT: 0.01},
    )

    with patch.object(BatteryInfo, "async_update", never_answers):
        assert await hub.async_refresh_modbus_data()

    assert hub.batteries == []
    assert [i.inverter_unit_id for i in hub.inverters] == [1]


