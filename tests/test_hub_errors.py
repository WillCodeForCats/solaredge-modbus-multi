@pytest.mark.parametrize(
    "error", [*TRANSPORT_ERRORS, ModbusExceptionError(2, "illegal address")]
)
async def test_unreadable_inverter_is_skipped_with_an_issue(hass, error):
    """An inverter that can't be read is skipped; with none left setup fails."""
    hub, site = _hub(hass, device_list=[1])
    site.for_unit(1).fail_read(40004, error)

    with pytest.raises(HubInitFailed, match="No usable inverters"):
        await hub.async_refresh_modbus_data()

    assert ir.async_get(hass).async_get_issue(
        DOMAIN, "setup_inverter_id_failed_entry1_1"
    )


