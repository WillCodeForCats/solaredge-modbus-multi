ENTRY_DATA = {"name": "SolarEdge", "host": "192.0.2.10", "port": 1502}
ALL_OPTIONS = {
    ConfName.DETECT_METERS: True,
    ConfName.DETECT_BATTERIES: True,
    ConfName.DETECT_EXTRAS: True,
    ConfName.ADV_STORAGE_CONTROL: True,
    ConfName.ADV_SITE_LIMIT_CONTROL: True,
}
METER_1_OFFSET = METER_1_BASE - 40121

TRANSPORT_ERRORS = [
    ModbusConnectionError("link down"),
    ModbusProtocolError("bad frame"),
    ModbusTimeoutError("no response"),
]


def _hub(hass, device_list=(1, 2, 3), options=None, site=None):
    """Build a hub for the simulated site."""
    hass.data[DATA_YAML] = {}
    site = site or simulated_site()
    hub = SolarEdgeModbusMultiHub(
        hass,
        "entry1",
        {**ENTRY_DATA, ConfName.DEVICE_LIST: list(device_list)},
        ALL_OPTIONS if options is None else options,
        site,
    )
    return hub, site


async def _ready_hub(hass, **kwargs):
    """Build a hub and run its setup refresh."""
    hub, site = _hub(hass, **kwargs)
    assert await hub.async_refresh_modbus_data()
    return hub, site


