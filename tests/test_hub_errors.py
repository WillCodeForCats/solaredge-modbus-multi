async def test_sleep_after_write_spaces_requests_until_settled(hass):
    """Requests are spaced after a write until the settle cycles pass."""
    hub, site = await _ready_hub(
        hass,
        device_list=[1],
        options={**ALL_OPTIONS, ConfName.SLEEP_AFTER_WRITE: 2},
    )
    inverter = hub.inverters[0]
    unit = site.for_unit(1)

    await inverter.write(inverter.site_limit_control_data, "E_Site_Limit", 4000.0)

    assert unit.message_spacing == 2
    assert hub._write_settle_cycles == {1: WRITE_SETTLE_CYCLES}

    # every component read counts as a refresh, so one refresh settles it
    await hub.async_refresh_modbus_data()

    assert unit.message_spacing == 0
    assert hub._write_settle_cycles == {}


async def test_write_settle_cycles_count_down(hass):
    """Each component read counts down the settle cycles before clearing."""
    hub, _ = await _ready_hub(hass, device_list=[1])
    inverter = hub.inverters[0]
    hub._write_settle_cycles[1] = 3

    await hub.component_update(1, inverter.inverter_data)
    assert hub._write_settle_cycles == {1: 2}

    await hub.component_update(1, inverter.inverter_data)
    await hub.component_update(1, inverter.inverter_data)
    assert hub._write_settle_cycles == {}


