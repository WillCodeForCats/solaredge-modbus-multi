INFO = "custom_components.solaredge_modbus_multi.helpers.async_get_connection_info"
ENTRY_DATA = {CONF_NAME: "SolarEdge", CONF_HOST: "Inverter.Local", CONF_PORT: 1502}
ENDPOINT = ModbusTcpParams(host="inverter.local", port=1502).endpoint


def _make_hub(hass, connection):
    hass.data[DOMAIN] = {"yaml": {}}
    return SolarEdgeModbusMultiHub(hass, "own_entry", ENTRY_DATA, {}, connection)


def _entries(hass, domains):
    """Make async_get_entry return an entry with the domain for each entry ID."""
    hass.config_entries.async_get_entry = MagicMock(
        side_effect=lambda entry_id: (
            MagicMock(domain=domains[entry_id]) if entry_id in domains else None
        )
    )


def _info(units, endpoint=ENDPOINT):
    return [ModbusConnectionInfo(endpoint=endpoint, connected=True, units=units)]


def _issue(hass):
    return ir.async_get(hass).async_get_issue(
        DOMAIN, "shared_connection_other_integration_own_entry"
    )


async def test_other_domain_on_same_endpoint_raises_issue(hass):
    """Test another integration holding the endpoint raises the issue."""
    hub = _make_hub(hass, SharedUnits({}))
    _entries(hass, {"own_entry": DOMAIN, "other": "solaredge_modbus"})

    with patch(INFO, return_value=_info({"own_entry": [1], "other": [1]})):
        hub._warn_if_shared()

    issue = _issue(hass)
    assert issue is not None
    assert issue.translation_placeholders["integrations"] == "solaredge_modbus"


