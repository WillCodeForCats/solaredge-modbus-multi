async def _start_user_flow(hass):
    return await hass.config_entries.flow.async_init(
        DOMAIN, context={"source": config_entries.SOURCE_USER}
    )


async def _choose(hass, result, next_step_id):
    return await hass.config_entries.flow.async_configure(
        result["flow_id"], user_input={"next_step_id": next_step_id}
    )


async def _run_scan(hass, setup_type, host="192.168.1.50", port=1502):
    """Drive the flow from the menu through to the scan_complete result."""
    result = await _choose(hass, await _start_user_flow(hass), setup_type)
    result = await hass.config_entries.flow.async_configure(
        result["flow_id"],
        user_input={CONF_NAME: "My Site", CONF_HOST: host, CONF_PORT: port},
    )
    assert result["type"] is FlowResultType.SHOW_PROGRESS
    assert result["step_id"] == "scan_ask_host"
    assert result["progress_action"] == "scanning_for_inverters"

    await hass.async_block_till_done()

    return await hass.config_entries.flow.async_configure(result["flow_id"])


async def _submit_manual(hass, **overrides):
    result = await _choose(hass, await _start_user_flow(hass), SETUP_MANUAL)
    user_input = {
        CONF_NAME: "My Site",
        CONF_HOST: "192.168.1.50",
        CONF_PORT: 1502,
        ConfName.DEVICE_LIST: "1",
        BYPASS_DEVICE_CHECK: False,
    }
    user_input |= overrides

    return await hass.config_entries.flow.async_configure(
        result["flow_id"], user_input=user_input
    )


async def _finish(hass, result):
    """Submit the features_info step."""
    assert result["type"] is FlowResultType.FORM
    assert result["step_id"] == "features_info"

    return await hass.config_entries.flow.async_configure(
        result["flow_id"], user_input={}
    )


