"""Tests for the user-initiated setup steps in config_flow.py.

Covers the user menu, the scan_fast/scan_full/scan_ask_host/scan_complete
scan path, the manual step, and the features_info step that both paths
end on. The device scanner is mocked, so no network traffic is made.

Every test ends in CREATE_ENTRY or ABORT. Tests that hit a form error
resubmit valid input afterwards to show the flow recovers.

Test file generated by Claude Code.
"""

