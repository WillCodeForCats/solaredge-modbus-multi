@pytest.mark.usefixtures("enable_custom_integrations")
async def test_scan_progress_shown_while_scan_running(hass, mock_scanner):
    """Configuring the flow mid-scan shows progress again, not a new scan."""
    release = asyncio.Event()

    async def scan_list(device_list, progress_callback):
        """Block until released, then find one inverter."""
        await release.wait()
        return [1]

    mock_scanner.scan_list.side_effect = scan_list

    result = await _choose(hass, await _start_user_flow(hass), SETUP_SCAN_FAST)
    result = await hass.config_entries.flow.async_configure(
        result["flow_id"], user_input=SCAN_INPUT
    )
    assert result["type"] is FlowResultType.SHOW_PROGRESS

    result = await hass.config_entries.flow.async_configure(result["flow_id"])
    assert result["type"] is FlowResultType.SHOW_PROGRESS
    assert result["step_id"] == "scan_ask_host"

    release.set()
    await hass.async_block_till_done()

    result = await hass.config_entries.flow.async_configure(result["flow_id"])
    result = await _finish(hass, result)

    assert result["type"] is FlowResultType.CREATE_ENTRY
    mock_scanner.cls.assert_called_once()
    mock_scanner.scan_list.assert_awaited_once()


