async def _start_user_flow(hass):
    """Start a user-initiated config flow."""
    return await hass.config_entries.flow.async_init(
        DOMAIN, context={"source": config_entries.SOURCE_USER}
    )


async def _choose(hass, result, next_step_id):
    """Pick a menu option in the user step."""
    return await hass.config_entries.flow.async_configure(
        result["flow_id"], user_input={"next_step_id": next_step_id}
    )


async def _submit_scan_host(hass, result, **overrides):
    """Submit the scan_ask_host form and wait for the scan to finish.

    Returns the result of scan_complete.
    """
    result = await hass.config_entries.flow.async_configure(
        result["flow_id"], user_input=SCAN_INPUT | overrides
    )
    assert result["type"] is FlowResultType.SHOW_PROGRESS
    assert result["step_id"] == "scan_ask_host"
    assert result["progress_action"] == "scanning_for_inverters"

    await hass.async_block_till_done()

    return await hass.config_entries.flow.async_configure(result["flow_id"])


async def _run_scan(hass, setup_type, **overrides):
    """Drive the flow from the menu through to the scan_complete result."""
    result = await _choose(hass, await _start_user_flow(hass), setup_type)
    return await _submit_scan_host(hass, result, **overrides)


async def _submit_manual(hass, result, **overrides):
    """Submit the manual form with MANUAL_INPUT plus any overrides."""
    return await hass.config_entries.flow.async_configure(
        result["flow_id"], user_input=MANUAL_INPUT | overrides
    )


async def _start_manual(hass, **overrides):
    """Drive the flow from the menu through one manual form submission."""
    result = await _choose(hass, await _start_user_flow(hass), SETUP_MANUAL)
    return await _submit_manual(hass, result, **overrides)


async def _finish(hass, result):
    """Submit the features_info step."""
    assert result["type"] is FlowResultType.FORM
    assert result["step_id"] == "features_info"

    return await hass.config_entries.flow.async_configure(
        result["flow_id"], user_input={}
    )


def _reset_scanner(mock_scanner):
    """Return the mock scanner to its default, successful behaviour."""
    mock_scanner.connect.side_effect = None
    mock_scanner.scan_list.side_effect = None
    mock_scanner.scan_list.return_value = [1]
    mock_scanner.check_list.return_value = {
        "inverters": [1],
        "other_devices": [],
        "no_response": [],
    }


async def _recover_scan_host(hass, result, mock_scanner):
    """Resubmit valid scan_ask_host input after an error and finish."""
    assert result["type"] is FlowResultType.FORM
    assert result["step_id"] == "scan_ask_host"
    _reset_scanner(mock_scanner)

    result = await _finish(hass, await _submit_scan_host(hass, result))

    assert result["type"] is FlowResultType.CREATE_ENTRY
    assert result["data"] == EXPECTED_DATA


async def _recover_manual(hass, result, mock_scanner):
    """Resubmit valid manual input after an error and finish."""
    assert result["type"] is FlowResultType.FORM
    assert result["step_id"] == "manual"
    _reset_scanner(mock_scanner)

    result = await _finish(hass, await _submit_manual(hass, result))

    assert result["type"] is FlowResultType.CREATE_ENTRY
    assert result["data"] == EXPECTED_DATA


