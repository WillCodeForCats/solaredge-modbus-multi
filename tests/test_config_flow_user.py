@pytest.mark.usefixtures("enable_custom_integrations")
@pytest.mark.parametrize(
    ("setup_type", "expected_range"),
    [
        (SETUP_SCAN_FAST, list(range(1, 33))),
        (SETUP_SCAN_FULL, list(range(1, 248))),
    ],
)
async def test_scan_creates_entry(hass, mock_scanner, setup_type, expected_range):
    """A successful scan goes to features_info, then creates the entry."""
    mock_scanner.scan_list.return_value = [1, 2]

    result = await _run_scan(hass, setup_type)
    result = await _finish(hass, result)

    assert result["type"] is FlowResultType.CREATE_ENTRY
    assert result["title"] == "My Site"
    assert result["data"] == {
        CONF_NAME: "My Site",
        CONF_HOST: "192.168.1.50",
        CONF_PORT: 1502,
        ConfName.DEVICE_LIST: [1, 2],
    }
    assert result["result"].unique_id == "192.168.1.50:1502"

    mock_scanner.cls.assert_called_once_with(
        host="192.168.1.50", port=1502, scan_retries=2, scan_timeout=0.7
    )
    mock_scanner.connect.assert_awaited_once()
    assert mock_scanner.scan_list.await_args.args[0] == expected_range
    mock_scanner.disconnect.assert_awaited_once()


