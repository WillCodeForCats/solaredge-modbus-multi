def _make_hub(hass, entry_id="test_entry", options=None):
    hass.data.setdefault(DOMAIN, {})["yaml"] = {}
    entry_data = {CONF_NAME: "SolarEdge", CONF_HOST: "127.0.0.1", CONF_PORT: 1502}
    return SolarEdgeModbusMultiHub(
        hass, entry_id, entry_data, options or {}, MockModbusConnection()
    )


async def _fake_init_device(self):
    """Stand in for reading InverterCommon, setting what device_info needs."""
    self.manufacturer = "SolarEdge"
    self.model = "SE10K"
    self.option = ""
    self.serial = "7E123456"
    self.name = f"SolarEdge I{self.inverter_unit_id}"
    self.uid_base = f"{self.model}_{self.serial}"
    self.hub.inverter_common[self.inverter_unit_id] = self.inverter_common


async def test_inverter_registration_success(hass):
    """The inverter is registered to the entry and can parent child devices."""
    entry = MockConfigEntry(domain=DOMAIN, data={}, options={})
    entry.add_to_hass(hass)
    hub = _make_hub(hass, entry.entry_id, options={ConfName.DETECT_METERS: False})

    with (
        patch.object(SolarEdgeInverter, "init_device", new=_fake_init_device),
        patch(
            "custom_components.solaredge_modbus_multi.hub.async_suns_scan_with_retry",
            new=AsyncMock(side_effect=ModbusError("no models")),
        ),
        patch.object(SolarEdgeInverter, "init_der_storage", new=AsyncMock()),
        patch.object(SolarEdgeInverter, "read_modbus_data", new=AsyncMock()),
    ):
        await hub._async_init_solaredge()

    assert len(hub.inverters) == 1
    inverter = hub.inverters[0]

    device_registry = dr.async_get(hass)
    device = device_registry.async_get_device_by_identifier(
        (DOMAIN, "SE10K_7E123456"), entry.entry_id
    )
    assert device is not None
    assert device.config_entry_id == entry.entry_id
    assert inverter.device_registry_id == device.id

    child = device_registry.async_get_or_create(
        config_entry_id=entry.entry_id,
        identifiers={(DOMAIN, "SE10K_7E123456_M1")},
        via_device_id=inverter.device_registry_id,
    )
    assert child.via_device_id == device.id


async def test_inverter_registration_error_fails_hub_init(hass):
    """A registry error on the mandatory inverter fails hub init."""
    hub = _make_hub(hass)
    error = DeviceInfoError(DOMAIN, {}, "duplicate identifiers")

    with (
        patch.object(SolarEdgeInverter, "init_device", new=AsyncMock()),
        patch.object(
            SolarEdgeInverter,
            "device_info",
            new_callable=PropertyMock,
            return_value=dr.DeviceInfo(identifiers={(DOMAIN, "serial")}),
        ),
        patch.object(
            dr.DeviceRegistry, "async_get_or_create", side_effect=error
        ) as get_or_create,
        pytest.raises(HubInitFailed, match="could not register device"),
    ):
        await hub._async_init_solaredge()

    get_or_create.assert_called_once()
    assert hub.inverters == []
