@pytest.mark.parametrize(("cls", "field", "options", "value", "kwargs"), STORAGE_CASES)
class TestStorageSelects:
    """Behavior shared by the storage control selects."""

    def _entity(self, cls, field, value, coordinator=None, **kwargs):
        """Build the entity with the given field value."""
        platform = _platform(**kwargs)
        setattr(platform.storage_control_data, field, value)
        return cls(platform, None, coordinator or _coordinator()), platform

    def test_available_and_current_option(self, cls, field, options, value, kwargs):
        """A valid value in remote control mode is available and shown."""
        entity, _ = self._entity(cls, field, value)
        if field != "control_mode":
            entity._platform.storage_control_data.control_mode = 4
        assert entity.available is True
        assert entity.current_option == options[value]

    @pytest.mark.parametrize(
        ("override", "update_ok", "kw"),
        [
            (None, False, {}),
            (None, True, {"has_storage_control": False}),
            (SunSpecNotImpl.UINT16, True, {}),
            (99, True, {}),
        ],
    )
    def test_unavailable(
        self, cls, field, options, value, kwargs, override, update_ok, kw
    ):
        """Unavailable when not updated, unsupported, or not a known value."""
        entity, _ = self._entity(
            cls,
            field,
            value if override is None else override,
            _coordinator(update_ok),
            **kw,
        )
        assert entity.available is False

    async def test_select_option(self, cls, field, options, value, kwargs):
        """Selecting an option writes its key and requests a refresh."""
        entity, platform = self._entity(cls, field, 0)

        await entity.async_select_option(options[value])

        platform.write.assert_awaited_once_with(
            platform.storage_control_data, field, value, **kwargs
        )
        entity.coordinator.async_request_refresh.assert_awaited_once_with()


