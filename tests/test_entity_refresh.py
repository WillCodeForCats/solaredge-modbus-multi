"""Tests for the refresh scheduled by SolarEdgeEntity after an action.

Test file generated by Claude Code.
"""

from types import SimpleNamespace
from unittest.mock import AsyncMock, MagicMock

from custom_components.solaredge_modbus_multi.entity import SolarEdgeEntity


async def test_schedule_refresh_runs_as_config_entry_background_task():
    """The refresh is handed to the config entry instead of being awaited."""
    platform = SimpleNamespace(device_info=None)
    config_entry = MagicMock()
    coordinator = SimpleNamespace(async_request_refresh=AsyncMock())
    entity = SolarEdgeEntity(platform, config_entry, coordinator)
    entity.hass = MagicMock()
    entity.entity_id = "number.inverter_1_site_limit"

    entity._async_schedule_refresh()

    config_entry.async_create_background_task.assert_called_once()
    hass, target, name = config_entry.async_create_background_task.call_args.args
    assert hass is entity.hass
    assert name == "number.inverter_1_site_limit refresh after action"
    coordinator.async_request_refresh.assert_not_awaited()

    await target

    coordinator.async_request_refresh.assert_awaited_once_with()
