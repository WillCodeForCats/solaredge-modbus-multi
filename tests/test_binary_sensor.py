def _problem_entity(status, vendor=None):
    """Return an inverter problem entity with a mocked hass bus."""
    platform = SimpleNamespace(
        uid_base="inverter_1",
        device_info=None,
        use_status_vendor4=False,
        inverter_data=SimpleNamespace(I_Status=status, I_Status_Vendor=vendor),
        cause_contexts={},
    )
    coordinator = SimpleNamespace(last_update_success=True, last_update_success_time=0)
    entity = InverterProblem(platform, None, coordinator)
    entity.hass = MagicMock()
    entity.entity_id = "binary_sensor.inverter_1_problem"
    entity.registry_entry = SimpleNamespace(device_id="dev1")
    entity._async_error_entity_id = MagicMock(return_value="sensor.inverter_1_error")
    return entity


def _update(entity, status):
    """Set the inverter status and run a coordinator update for a new poll."""
    entity._platform.inverter_data.I_Status = status
    entity.coordinator.last_update_success_time += 1
    with patch.object(entity, "async_write_ha_state"):
        entity._handle_coordinator_update()


def _fired(entity):
    """Return the event data of each problem event fired."""
    calls = entity.hass.bus.async_fire.call_args_list
    assert all(c.args[0] == EVENT_PROBLEM for c in calls)
    return [c.args[1] for c in calls]


def test_problem_event_on_fault_with_cause():
    """Turning on fires an event with the cause, and the state uses its context."""
    entity = _problem_entity(4, vendor=17)
    _update(entity, 4)
    assert _fired(entity) == []

    _update(entity, 7)

    assert _fired(entity) == [
        {
            "device_id": "dev1",
            "status_value": 17,
            "status_text": VENDOR_STATUS[17],
            "error_entity_id": "sensor.inverter_1_error",
        }
    ]
    context = entity.hass.bus.async_fire.call_args.kwargs["context"]
    assert entity._context is context


def test_problem_event_not_repeated_while_on():
    """No new event while the problem stays on."""
    entity = _problem_entity(4)
    _update(entity, 7)
    _update(entity, 7)
    assert len(_fired(entity)) == 1


def test_problem_event_not_fired_when_cleared():
    """Turning off after a fault does not fire an event."""
