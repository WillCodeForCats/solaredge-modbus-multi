async def test_yaml_modbus_section_raises_deprecation_issue(hass):
    """A modbus section in YAML raises an issue, which clears once removed."""
    issue_registry = ir.async_get(hass)

    assert await async_setup(hass, {DOMAIN: {"modbus": {"timeout": 3}}})
    assert hass.data[DATA_YAML] == {"modbus": {"timeout": 3}}
    assert issue_registry.async_get_issue(DOMAIN, "deprecated_yaml_modbus")

    assert await async_setup(hass, {DOMAIN: {"retry": {"limit": 2}}})
    assert hass.data[DATA_YAML] == {"retry": {"limit": 2}}
    assert issue_registry.async_get_issue(DOMAIN, "deprecated_yaml_modbus") is None


