def _entry(hass, version, minor_version, data, options=None, unique_id="old"):
    """Add a config entry at the given version."""
    entry = MockConfigEntry(
        domain=DOMAIN,
        version=version,
        minor_version=minor_version,
        data=data,
        options=options or {},
        unique_id=unique_id,
    )
    entry.add_to_hass(hass)
    return entry


async def test_migrate_from_version_1(hass):
    """Version 1 moves scan_interval to options and builds the device list."""
    entry = _entry(
        hass,
        1,
        0,
        {
            "name": "SolarEdge",
            "host": "192.0.2.10",
            "port": 1502,
            "scan_interval": 30,
            "device_id": 3,
            "number_of_inverters": 2,
        },
        {"detect_meters": True},
    )

    assert await async_migrate_entry(hass, entry)

    assert (entry.version, entry.minor_version) == (2, 3)
    assert entry.data == {
        "name": "SolarEdge",
        "host": "192.0.2.10",
        "port": 1502,
        "device_list": [3, 4],
    }
    assert entry.options == {"detect_meters": True, "scan_interval": 30}
    assert entry.unique_id == "192.0.2.10:1502"


