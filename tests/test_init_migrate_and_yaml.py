@pytest.mark.parametrize("keep_modbus_open", [True, False])
async def test_migrate_from_version_2_1_removes_keep_modbus_open(
    hass, keep_modbus_open
):
    """Version 2.1 drops keep_modbus_open and raises an issue if it was set."""
    entry = _entry(
        hass,
        2,
        1,
        {"name": "S", "host": "192.0.2.10", "port": 1502},
        {"keep_modbus_open": keep_modbus_open, "detect_meters": False},
        unique_id="192.0.2.10:1502",
    )

    assert await async_migrate_entry(hass, entry)

    assert entry.options == {"detect_meters": False}
    assert entry.unique_id == "192.0.2.10:1502"
    issue = ir.async_get(hass).async_get_issue(
        DOMAIN, f"deprecated_keep_modbus_open_{entry.entry_id}"
    )
    assert (issue is not None) is keep_modbus_open


